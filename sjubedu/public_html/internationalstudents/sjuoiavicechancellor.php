                 <p>Dear International Student,
<p>We invite you to join St. Joseph’s University, Bengaluru to have brilliant higher education career journey of your life and enrich your professional talent at one of the oldest higher education institutions in India established in 1882.</p>

<p>The University is administered by the Society of Jesus (SJ), also known as the Jesuits founded by St. Ignatius of Loyola in 1540. With their headquarters in Rome, Italy, the Jesuits are actively involved with mission of providing quality education and character formation in nearly fifty countries of the world and run such reputed world class Universities like Universidad de Buenos Aires, Argentina, Pontificia Universidad Catholica de Rio de Jameiro, Brazil, St. Mary’s University, Halifax, Canada, Sophia University, Tokyo-Japan, Champion Hall – Oxford University, U.K., Boston College, Massachusetts, U.S.A., Fordham University, U.S.A., Georgetown University, Washington D.C., U.S.A., Loyola University, Chicago, U.S.A., University of San Francisco, U.S.A., Sogang University, Seoul, South Korea, IQS Barcelona, Spain, Sanata Dharma University, Indonesia, etc.</p>

<p>The Jesuits came to India in 1542 under the leadership of St. Francis Xavier and established the first ever higher education institution in India – St. Paul’s College, Goa the same year (which underwent several transformations). Subsequently they established a large number of schools, colleges and seminaries in Goa and also in other prominent towns and cities of India. Most of the more than 100 year old and not for profit colleges in India are presently run by the Society of Jesus like St. Joseph’s, Trichy, St. Xavier’s, Kolkata, St. Xavier’s, Mumbai, Loyola, Chennai, St. Aloysius, Mangalore, etc.</p>

<p>Our Institution founded as St. Joseph’s College in 1882 has a glorious history of high academic achievements of more than 140 years. On 2nd July 2022 the St. Joseph’s College, Bangalore was elevated to the status of an University by the Government of Karnataka under the R.U.S.A. (Rashtriya Uchchatar Siksha Abhiyan) Scheme of the Government of India, Ministry of Human Resource Development, New Delhi. St. Joseph’s University, Bangalore has the unique distinction as being, the only private college in India to be raised to this status of the first of its kind Public – Private Partnership (PPP) University in India!</p>

<p>On 27th September 2022, Her Excellency Smt. Draupadi Murmu, President of India, formally inaugurated the St Joseph’s University in the august presence of Hon’ble Shri Thaawar Chand Gehlot, Governor of Karnataka, Hon’ble Shri Basavaraj Bommai, Chief Minister, Hon’ble Shri C. Ashwath Narayan, Minister for Higher Education of the State and Rt. Rev. Dr. Peter Machado, Archbishop of Bangalore.</p>
<p>
The Bangalore Jesuit Educational Society (Regd) has already embarked on a mission to develop the University as a centre to provide world class education at affordable cost to all deserving young people irrespective of their caste, creed, economic status or nationality keeping in mind the triple values of academic excellence, character formation and social concern.</p>

<p>Plans are afoot to augment the infrastructure facilities like library, laboratories, computer and network system, hostels and cafeterias, sports grounds and gymnasiums, auditoriums and seminar halls, astronomical observations, student health and counselling centres, placement and skills development cells, etc at the present Lal Bagh Road Campus and also to build a huge state of the art new campus to cater to all the future expansions needs of the University in a 30 acres – Mount Saint Joseph, Bannerghatta Road in next five years time from now.</p>

<p>Saint Ignatius of Loyola had a keen desire to spread education and knowledge, media of liberation for a just and equitable society. The group he founded, the Society of Jesus, has been active in the field of education throughout the world since its origin. In the world, the Jesuits are responsible for 3,897 Educational Institutions in 96 countries. The education imparted by the Jesuits aims at the integral, personal formation of youth.</p>

