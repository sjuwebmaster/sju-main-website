        <h5 class="fw-bold mt-4">3. Health Insurance during Stay in India</h5>
        <p>All international students are required to have a valid International Health Insurance Policy with an adequate sum assured/sufficient coverage. The policy should cover medical emergencies and hospitalization for the entire duration of their stay in India (for e.g. 3 years for UG course and 2 years for PG course).</p>

        <h5 class="fw-bold mt-4">4. Travel</h5>
        <p>Students need to produce a Residential Permit (RP) at the time of departure/arrival wherever such travel documents are required (may have to surrender the Residential Permit (RP) to the immigration officer at the concerned airports at the time of final departure on course completion).</p>
