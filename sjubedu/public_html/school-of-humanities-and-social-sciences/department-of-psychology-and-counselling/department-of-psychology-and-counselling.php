           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department of Psychology was established in the year 2013. The Department aims to help students develop a deep understanding of the multifaceted nature 
          of the human personality, the wellsprings of motivation and interpersonal relationships so as to be able to contribute to the well-being of humanity. 
          The mission of the Department is to achieve excellence that generates new knowledge through research and internships, and also to make students emotionally 
          mature and creative in their responses to life situations. The Department offers both Undergraduate and Postgraduate programmes.</p>

          <p>The Department has passionate faculty engaged in counselling, training and research. Students are involved in internships, field visits, and certificate courses and are 
          given broad exposure to the subject in order to gain an understanding of the cultural context of Psychology and mental health. The Department had signed a Memorandum of 
          Understanding with International Universities; the students have visited Singapore, Kuala Lumpur, Malaysia, presented papers on the theme of Mental Health literacy, and 
          students also visited the Green School in Bali to gain global exposure in the past two years. The Department has also collaborated with various organisations around the 
          country to offer our students a wide variety of certificate courses and internship opportunities. The Department organises international and national conferences, seminars, 
          workshops, and webinars on the themes of mental health, gender issues, neurodiversity, LGBTQIA, child sexual abuse and intimate partner violence.</p>
