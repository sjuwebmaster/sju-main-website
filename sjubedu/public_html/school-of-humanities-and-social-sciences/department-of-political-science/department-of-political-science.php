           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The BA degree programme was started in erstwhile St Joseph’s College, in the year 1926. The students were admitted to BA programme in 
          July 1926. Fr J Argaunt, Principal of the College during the years (1924-1926), played a key role in the introduction of BA programme.</p>

          <p>During the early 1920s, different subjects were taught under the nomenclature of History, Economics, Political Science and Logic. 
          All these subjects were under the Department of Social Sciences. The Department of Social Sciences was headed by a single professor 
          for a long time. The last professor to hold such a position was Prof S Asirvatham. The Department system came into existence only in 
          the year 1962, with each Department headed by a professor. The Department of Political Science came into existence the same year.</p>

          <p>The Department of Political Science during the last ninety-five years has been served by eminent  Professors like PM Francis, Michael, 
          S Clement, Balakrishna, Dr Benny Peters, Fr Ambrose Pinto SJ, Fr Francis D’Almeda SJ, Prof Jerome Nirmal Raj and many others. Dr Benny Peters 
          secured PhD degree in the year 1993 and has the unique honor of being the first PhD holder to teach in the Humanities section.</p>
