           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department of History is one of the first departments started in the Institution dating back to the 1930s. The students 
          tend to be heterogeneous, ranging from those well-read, who possess a good deal of insight and have a clear goal as to what they 
          want to do in life to the larger percentage in the class who for reasons academic, economic, and social, need basic assistance, 
          encouragement and follow up.  In this context, the Department does a lot of remedial work to help academically weaker students 
          perform better. Students tend to be varied, ranging from those who are well-read, possess a great deal of insight, and have a 
          well-defined life objective to the majority of the class who, for academic, economic, and social reasons, require basic input, 
          support, encouragement, and follow-up. The Department strives to make history instruction engaging, informative, and pertinent. 
          Consistent use of audiovisuals is employed to supplement the information. While conducting a class, efforts to inculcate a spirit 
          of inquiry among the students are encouraged. Wall maps, models, pictures, etc., are used to supplement data. The Department runs 
          a History Association titled ‘Parishodhana'. Through its own newsletter, 'The Pendulum,' the Department encourages students to 
          explore with their research abilities. The Department of History also conducts its annual 60 hour Certificate Credit Course on 
          ‘Gleaning India’s History through Numismatics’. </p>
