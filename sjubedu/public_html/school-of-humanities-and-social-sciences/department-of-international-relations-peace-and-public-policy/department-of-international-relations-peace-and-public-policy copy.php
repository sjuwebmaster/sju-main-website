           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department of International Relations, Peace and Public Policy at St Joseph's University offers a distinctive curriculum that balances theory and practice. 
          With our programmes offering super specialisations within the larger field of Political Science in the disciplines of International Relations, Public Policy and Peace 
          and Conflict Studies, our Department aims to develop a cohort that is prepared for diverse careers in academia, research, administration and government.</p>

          <p>Through our carefully designed curriculums, we strive to inculcate the ideals of peaceful conflict resolution, teach the importance of understanding the 
          root causes of conflict, and pursue non-violent means to transform societies. We aim to cultivate critical thinking with theoretical and conceptual insights 
          to bring socio-economic transformation through policy-making machineries. With this comprehensive approach, we provide our students with the space and opportunity 
          to develop academic rigour and scope for greater learning.</p>

          <p>Today, in an era of globalisation, the world is experiencing new-age challenges like civil unrest, unconventional violence, conflicts, climate change, 
          terrorism, refugee crisis, and human rights violations, among many others. Simultaneously, we are also in an era of rapid growth, change, and never before 
          seen opportunity for India, on both domestic and international levels, where it is becoming the need of the hour for there to be policies that equip India 
          both on a global and domestic realm to use these opportunities and tackle the new age challenges.</p>

          <p>Through our distinctive programmes, we are committed to preparing our students with the knowledge and tools required to develop a deeper understanding 
          to critically interpret the complexities of contemporary global and domestic challenges and identify policy solutions and avenues of cooperation, thus 
          equipping the students in contributing to address these global challenges and be a part of the change.</p>
