        <article class="mb-5 mt-4">
            <div class="title-area pb-2">
                <h2 class="fw-bold mb-3 text_blue">Programme Officer - Duties and Functions</h2>
            </div>
            
            <p class="lead mb-4" style="font-size: 1.1rem; color: #555;">
                The Programme Officer is expected to motivate student youth to understand the values and philosophy of N.S.S. The overall function of the programme officer is to help students plan, implement, and evaluate NSS activities and provide proper guidance and direction.
            </p>

            <p class="mb-5">To discharge their obligations, the programme officer plays multiple roles to improve the quality and magnitude of the NSS programme in the institution.</p>

            <div class="row g-4 mb-5">
                
                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-diagram-3 role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As an Organizer</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Interpret the scheme to students and the college community to create awareness.</li>
                                <li>Motivate, recruit, and select students for NSS work.</li>
                                <li>Enlist cooperation and coordination of community agencies, government departments, and NGOs.</li>
                                <li>Select service projects based on utility and feasibility.</li>
                            </ul>
                        </div>
                    </div>
                </div>

                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-book role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As an Educator</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Orient volunteers by explaining the concept of social service and teaching necessary methods and skills.</li>
                                <li>Promote community education through meetings, talks, news bulletins, and discussions.</li>
                                <li>Help formulate NSS programmes that have direct relationships with the academic curricula.</li>
                            </ul>
                        </div>
                    </div>
                </div>

                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-link-45deg role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As a Coordinator</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Coordinate NSS activities in accordance with student abilities and community demands.</li>
                                <li>Coordinate internal teaching expertise to enhance student knowledge and skills.</li>
                                <li>Coordinate external resources (government services, welfare agencies, voluntary bodies) for NSS success.</li>
                            </ul>
                        </div>
                    </div>
                </div>

                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-eye role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As a Supervisor</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Assist students in learning how to do their jobs effectively.</li>
                                <li>Use supervisory skills to enable students to set realistic goals, view problems as challenges, and take appropriate steps to solve them.</li>
                                <li>Assist in evaluation and follow-up work.</li>
                            </ul>
                        </div>
                    </div>
                </div>

                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-clipboard-data role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As an Administrator</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Keep the principal, advisory committee, and university programme coordinator informed.</li>
                                <li>Run day-to-day administration and attend to correspondence.</li>
                                <li>Maintain records of student participation and activities.</li>
                                <li>Prepare periodic progress reports and annual calendars.</li>
                                <li>Keep accounts and stock in prescribed forms.</li>
                            </ul>
                        </div>
                    </div>
                </div>

                <div class="col-md-6">
                    <div class="card h-100 border-0 bg-light shadow-sm role-card">
                        <div class="card-body">
                            <div class="d-flex align-items-center mb-3">
                                <i class="bi bi-megaphone role-icon me-3"></i>
                                <h5 class="fw-bold text_blue mb-0">As a Public Relation Officer</h5>
                            </div>
                            <ul class="mb-0 text-muted" style="font-size: 0.95rem;">
                                <li>Inform the community about the scheme through press reports, radio/TV programmes, pamphlets, and seminars.</li>
                                <li>Initiate IEC campaigns for image building of NSS to inspire students and the community.</li>
                            </ul>
                        </div>
                    </div>
                </div>

            </div> <hr class="my-5 border-2 text-muted opacity-25">

            <div class="title-area pb-2">
                <h3 class="fw-bold mb-3 text_blue">Selection of the Programme Officer</h3>
            </div>
            <p class="mb-4">The selection of the programme officer will be made by the principal of the institution in consultation with the programme coordinator of the University.</p>

            <div class="row g-4">
                <div class="col-12">
                    <div class="left_title_border mb-2">
                        <h4 class="br_title text_blue fw-bold fs-5"><span></span> a. Qualifications</h4> 
                    </div>
                    <div class="ps-3 border-start">
                        <ul class="mb-0 text-muted">
                            <li>Programme Officers will be selected from the members of the teaching faculty only.</li>
                            <li>NCC Officers and physical education directors should not be appointed as NSS programme officers.</li>
                            <li>In women's colleges or for a women's unit, a lady teacher should be appointed. Male members may assist the lady programme officers.</li>
                            <li>A teacher who has a high level of motivation towards community work and a good rapport with students should be preferred.</li>
                        </ul>
                    </div>
                </div>

                <div class="col-12 mt-4">
                    <div class="left_title_border mb-2">
                        <h4 class="br_title text_blue fw-bold fs-5"><span></span> b. Tenure</h4> 
                    </div>
                    <div class="ps-3 border-start">
                        <p class="text-muted mb-0">The maximum period for which a teacher is appointed as programme officer will be 3 years in the first instance. However, this period is extendable for two more years based on a review of their performance by the principal and programme coordinator.</p>
                    </div>
                </div>

                <div class="col-12 mt-4">
                    <div class="left_title_border mb-2">
                        <h4 class="br_title text_blue fw-bold fs-5"><span></span> c. Training / Orientation</h4> 
                    </div>
                    <div class="ps-3 border-start">
                        <p class="text-muted mb-2">The programme officer will be sent for an orientation course within 3 months of selection. They must undergo the training within one year of appointment if no course is conducted in the stipulated 3-month period.</p>
                        <p class="text-muted mb-2">The principal will intimate the programme coordinator, NSS Regional Centre, and TORC/TOC regarding the selection, and ensure the officer attends the orientation. It is the head of the institution's obligation to relieve the officer for this purpose.</p>
                        <p class="text-muted mb-0">If the selected officer does not undergo orientation training for any reason within one year of selection, they will cease to function as a programme officer, and another person will be selected and trained. No programme officer will continue to work without proper orientation within the stipulated period.</p>
                    </div>
                </div>
            </div>

