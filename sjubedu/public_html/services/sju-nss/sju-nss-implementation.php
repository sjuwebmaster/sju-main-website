                                <p class="card-text text-muted">A stock-register, listing separately the consumable and non-consumable items, should be maintained. In addition, an issue/lending register must be maintained for the purpose of verification and periodic stock-checking. The entries in the stock-register will be initialed or countersigned by the Head of the institution.</p>
                            </div>
                        </div>
                    </div>

