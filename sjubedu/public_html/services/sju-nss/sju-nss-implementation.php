                                <p class="card-text text-muted">This register is to be maintained by the programme officer with the help of students. It should provide a list of the projects undertaken during the year with complete information on each project, viz; places/areas/institution, target groups, number of students (also names) involved in the particular activity and financial allotment.</p>
                            </div>
                        </div>
                    </div>

                    <div class="col-md-6">
