                                <p class="card-text text-muted mb-3">While the college office is responsible for separately maintaining accounts for NSS ensuring their audit, the programme officer concerned should keep himself/herself informed of the progress of the expenditure and be aware of the accounting procedure adopted by the institution office. He/she would ensure submission of expenditure statement and utilization certification to the university/state government in time.</p>
                                <p class="card-text text-muted mb-3">Colleges having more than one NSS unit may select one of the programme officers to look after the accounts, records, reports, and returns etc. The accounts regarding the receipt of NSS grants and their utilization will be maintained as per financial norms. These accounts will be open for inspection to audit parties, officers of NSS organization, State Liaison Officer, and Programme Coordinator also. NSS accounts will be maintained separately and will not be integrated with other accounts of the institution.</p>
                                <p class="card-text text-muted mb-0">The programme officers will send periodical reports to the NSS programme coordinator on the prescribed proforma. Copies of such reports will be endorsed to the NSS Regional Centre and State Liaison Officer. Reports of special camping projects undertaken by the NSS units may also be sent to the programme coordinator, under intimation to the NSS Regional Centre and State Liaison Officer for information and projection at an appropriate level.</p>
