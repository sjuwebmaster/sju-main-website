                    <h3 class="br_title text_blue fw-bold"><span></span> b. Records and Registers</h3> 
                </div>
                <p>The NSS programme is financed by public funds. Therefore, the institution should maintain the financial records and registers as required under financial rules, and these have to be kept open for inspection and audit.</p>
                <p class="mb-4">The records and registers should be properly handed over by the outgoing programme officer to the newly appointed programme officers. The following records and registers are to be maintained in the NSS units at the College level:</p>
                
                <div class="row g-4">
                    
                    <div class="col-md-6">
                        <div class="card h-100 border-0 shadow-sm">
                            <div class="card-body">
                                <h5 class="fw-bold text_blue mb-3"><i class="bi bi-person-lines-fill text-warning fs-4 me-2 align-middle"></i> Enrolment Register</h5>
                                <p class="card-text text-muted">A register with complete particulars and profiles of the students enrolled in NSS should be maintained, unit-wise. This register should have information about the names, sex, SC/ST, and class of NSS students, their interests, and experience in NSS and other service activities.</p>
                            </div>
                        </div>
                    </div>

                    <div class="col-md-6">
                        <div class="card h-100 border-0 shadow-sm">
                            <div class="card-body">
