                <h2 class="fw-bold mb-3 text_blue">
                   National Service Scheme (N.S.S)
                </h2>
            </div>
            
            <p>The National Service Scheme (NSS) is an Indian government-sponsored public service program conducted by the Ministry 
            of Youth Affairs and Sports of the Government of India. Popularly known as NSS, the scheme was launched in Gandhiji's Centenary year in 1969. </p>

            <p>St Joseph's University has been continuously in NSS since its inception with the major aim of providing opportunities to the students to 
            involve themselves in social activities and ultimately developing their personality. It is also known to have one of the oldest NSS units in 
            Karnataka State, has completed 50 years, reflecting the essence of democratic living and upholding the need for selfless service empowering 
            youth and promote national integration.</p>

            <p>Service of faith and promotion of justice is a significant component of Jesuit education across the globe. It is imperative that our 
            education need to make our students have a deep and profound faith in themselves, in each other and the divine, which needs to be realized 
            in the promotion of justice for all, especially the last, the least, and the lost who are on the periphery of society. Ultimately we need to 
            prepare students who serve the nation with resolute devotion and single-minded commitment.</p>

            <p>National Service Scheme is a voluntary organization of young students that provides services to society without bias. It aims to doctrine 
            social welfare in students through community services. Students are the building blocks of society. It is a proven fact that organized group 
            activities are potential enabling factors for cognitive developments and enriching the spirit of brotherhood. We at NSS, strive to achieve 
            similar goals through activities which have a direct impact on the society and environment at large</p>
