                    <p class="lead" style="font-style: italic; color: #555; border-left: 4px solid #ffc107; padding-left: 15px;">
                        "It gives me immense pride and satisfaction to reflect on the remarkable journey of our NSS volunteers at St Joseph's University."
                    </p>

                    <p>Over the years, this program stands as a true testament to the dedication, leadership, and unwavering commitment of our students towards community service and nation-building. Our volunteers have consistently brought laurels to the institution through participation in prestigious platforms like National Integration Camps fostering cultural exchange and unity in diversity, State Youth Festivals showcasing talents and team spirit, inter-college competitions securing overall winner positions across diverse fields, and special honors such as representing the Karnataka contingent in the State Republic Day parade.</p>

                    <p>Since the National Service Scheme's inception in 1969—with our unit proudly celebrating its Golden Jubilee in 2019—we have embodied the motto <strong>“Not Me, But You,”</strong> empowering youth through hands-on service that promotes social welfare, awareness, and mutual respect.</p> 

                    <h5 class="text_blue fw-bold mt-4 mb-3">Key Initiatives</h5>
                    <ul class="mb-4">
                        <li class="pb-2">Blood donation camps addressing shortages in government hospitals.</li>
                        <li class="pb-2">First aid workshops, mental health sessions, and personality development programs for life-saving skills and well-being.</li>
                        <li class="pb-2">Cleanliness drives, World Environment Day celebrations, and sustainability efforts for hygiene and environmental health.</li>
                        <li class="pb-2">Road safety campaigns to reduce accidents.</li>
                        <li class="pb-2">Daily human rights observances uniting diverse groups to uphold dignity and respect.</li>
                        <li class="pb-2">NSS Exposure Camps helping volunteers grasp rural socio-economic and cultural realities while inculcating empathy and oneness.</li>
                    </ul>

                    <p>Our volunteers work tirelessly, day and night, to support the needy and elevate lives with dignity. These accomplishments reflect the collective efforts of our NSS family—dedicated volunteers, student leaders, supportive faculty, and well-wishers—building compassion, discipline, leadership, and civic responsibility. Looking ahead, I am confident this spirit will continue inspiring greater enthusiasm and societal impact.</p>
