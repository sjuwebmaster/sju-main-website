             <p>St Joseph's University (SJU) is a Jesuit university at the heart of Bengaluru, the Silicon City of India. 
             Established in 1882 by Paris Foreign Fathers, the college management was handed over to the Jesuit order 
             (Society of Jesus) in 1937. The college was first affiliated with the University of Madras and later with 
             the Mysore and Bangalore universities. In 1986, St Joseph's College became the first affiliated college in 
             Karnataka to offer postgraduate courses. In 1988, it became the first college in Karnataka to get a research 
             center, and in 2005, it was one of the five colleges in Karnataka that was awarded academic autonomy. 
             In February 2021, the St Joseph's University bill was presented in the Karnataka Legislative Assembly 
             and was subsequently passed by the Legislative Assembly and Karnataka Legislative Council. The college 
             received its University status on 2nd July 2022 and was inaugurated as India's first public-private university 
             by the Hon'ble President of India, Smt. Droupadi Murmu on 27th September 2022.</p>
            
            
