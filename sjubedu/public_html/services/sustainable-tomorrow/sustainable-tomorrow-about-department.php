             <p>The School of Chemical Sciences at St Joseph's University comprises the Department of Chemistry (established in 1927) 
             and the Department of Biochemistry (established in 2020). It offers undergraduate, postgraduate and doctoral programmes 
             in chemistry and  undergraduate programmes in biochemistry. Known for its highly qualified faculty and carefully curated 
             syllabi, the school emphasizes analytical thinking through research-based pedagogical tools and project work, leading to 
             student publications in renowned journals.</p>

             <p>The school's research facilities include advanced scientific instruments, enabling work in catalysis, materials chemistry, 
             electrochemistry, organic synthesis and protein chemistry. The academic staff has guided over 35 Ph.Ds and, published more than 
             400 research publications in peer-reviewed journals, and received support from prestigious funding agencies. The Department has 
             earned DBT-STAR and DST-FIST recognition. It collaborates nationally and internationally with highly reputed institutions and is 
             supported by MOU with chemical industries.</p>

             <p>The undergraduate and postgraduate Chemical societies organize various activities, including lectures by prominent scientists, 
             inter-collegiate events and outreach programs. The chemistry department strives for academic excellence to develop skilled chemists 
             who contribute positively to the society.</p>
            
            
