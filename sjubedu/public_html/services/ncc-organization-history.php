                   1 MYSORE ARMD SQN NCC was raised on 12 June 1962 and was later re-designed as 21 MYSORE ARMD NCC in December 1962. 
                   Major S.K. Dhamija of CIH was the first Commanding officer who commanded from 1st September 1962 to 14th June 1965. 
                   Again, on 17th April 1964, the squadron was re-designed as 1 MYSORE ARMD SQN NCC and further 1 MYSORE ARMD SQN NCC 
                   was re designed as 1 KAR ARMD SQN NCC on 1st November 1974.
                 </p>
               </div>

               <div class="timeline-data">
                 <p>
                   1 KAR ARMD SQN NCC was redesigned as 1 KAR (1) COY on April 2004. It was reversed back to 1 KAR ARMD SQN NCC on 14th September 2004. 
                   2/Lt Albert S was an infantry battalion officer who later attended the armed corps special course at Ahmednagar and got commissioned 
                   as ANO of 1 MYSORE ARMD SQN NCC in 1964.
                 </p>
               </div>
               
               <div class="timeline-data">
                 <p>
                   In 1984 Prof Jacob Raju P was commissioned as 2nd lieutenant as ANO of 1 KAR ARMD SQN NCC of St. Joseph's College. In 1981, 
