          <h3 class="fw-bold text_blue mb-3">Why Outreach?</h3>
          <p>The Outreach program draws its inspiration from the University's vision of formimg women and men for others. 
          It will provide students with a platform to explore and develop the art of critical thinking, the skill of leadership 
          and techniques of meaningful interventions aimed at building a just equitable society . It further draws its roots from 
          the Brizilian educator Paulo Friere's Philosophy of Action – Reflection – Praxis.</p>

          <p>In the view of the UGC and the NAAC recommendations on Extension, the objective of the outreach programme is to extend 
          knowledge and other institutional resources to the community and vice – versa. It is two – way process between the institution 
          and the people, an intellectual intervention in the community's living problems which need to be overcome through an educational 
          process. Extension is a perfect blend of theory with practice.</p>

          <p>It will orient the students with the skills required in community development and would sensitize them towards various issues 
          of these marginalized groups and instill enough confidence and satisfaction for taking up the cause of the development of those groups.</p>

          <p>As the name of the programme itself – BEMBALA suggests, it aims to reach out the deprived groups and vulnerable sections of society and 
          create opportunities for education , awareness and skill enhancement. It intend to create a learning process for faculty and students through 
          exposure to comminity needs, problems, and issues. It hopes to reach out to the community by designing need based interventions and generating research.</p>

          <p>Eventually it will facilitate networking and linkages of the community with NGOs, institutions, and government agencies for the effective service 
          delivery and advocacy support. It also hopes to link up with the corporate sector within the parameters of Corporate Social Responsibilities ( CSR )</p> 
