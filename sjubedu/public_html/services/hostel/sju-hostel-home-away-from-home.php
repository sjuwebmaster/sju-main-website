           <p>St Joseph's University Boys Hostel, located on the campus, is a 75-year-old hostel and celebrated its platinum jubilee on 26 January 2023. 
           It has been home to some brilliant and renowned minds of this institution. With its well-designed infrastructure and essential amenities, 
           it provides a comfortable and conducive environment for students' boarding needs and recreational activities.</p>

           <p>One of the remarkable aspects of the hostel is its architectural beauty, due to which the hostel block building stands out as a remarkable specimen, 
           making it a heritage building. The hostel building, constructed in 1948, boasts a unique semi-circular or crescent-shaped design. The building itself is made of stone, 
           giving it a timeless and elegant appeal and showcasing the university's commitment to preserving its rich heritage. The green plants and the flowering bougainvillea add 
           to the overall aesthetic appeal.</p>

           <p>Inside the hostel, there are various facilities to cater to the students' needs. The hostel offers single rooms for accommodation, ensuring privacy 
           and personal space for each resident. Additionally, there are large halls, including a prayer hall, which serve as common areas for socialising, studying, 
           and engaging in group activities. Over time, some of these halls have been converted into cubicles, increasing the accommodation capacity of the hostel.</p>

           <p>To promote a healthy and well-balanced lifestyle the hostel has its own canteen. The canteen operates on a cooperative basis, providing students with 
           hygienic and nutritious meals. This facility not only saves students the hassle of cooking but also serves as a gathering place where the residents can 
           enjoy tasty food while fostering a sense of community among themselves.</p>

           <p>Additionally, St Joseph's University also has a second hostel for boys, located in Ejipura, approximately 4 kilometers away from the university campus. 
           This additional hostel, known as St Berchman's Hostel, can accommodate 20 boys and offers dormitory facilities. The university is actively working on arranging a 
           canteen facility to cater to the residents' dining needs.</p>

           <p>Overall, St Joseph's University Hostel and its extension, St Berchman's Hostel, provide a safe, comfortable, and nurturing living space for students 
           pursuing their education. With its well-maintained infrastructure, essential amenities, and a supportive community, the hostels truly serve as a home 
           away from home for the students, allowing them to focus on their studies and personal growth.</p>
