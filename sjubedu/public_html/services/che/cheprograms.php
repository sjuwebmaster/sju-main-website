	<h4>Ignitors 3 - Professional Skills & Kairos</h4>
<p><strong>Professional Skills:</strong> This program focuses on building essential professional skills to prepare students for successful placements and workplace readiness. Through hands-on sessions, students develop core competencies, emphasising resume writing, interview techniques, Group Discussion, and workplace etiquette, while also nurturing soft skills such as accountability and ownership. Using real-world scenarios and role-play exercises, students gain confidence and clarity in navigating professional environments. Designed to bridge academic learning with industry expectations, this program empowers students to present themselves effectively, collaborate with impact, and thrive in diverse organisational settings.</p>
			  
<p><strong>Kairos (Gratitude Program):</strong> The Gratitude Program is a heartfelt initiative designed for students in their final semester to reflect on their college journey and express appreciation for the people and experiences that shaped them. Through guided activities, sharing circles, and creative expressions, students honour mentors, peers, and personal growth. The program fosters closure, community, and celebration—encouraging students to acknowledge challenges overcome and lessons learned. It culminates in a meaningful ceremony where gratitude becomes a bridge to future aspirations. This reflective space helps students transition with clarity, humility, and a deep sense of connection to their college legacy.</p>		  
