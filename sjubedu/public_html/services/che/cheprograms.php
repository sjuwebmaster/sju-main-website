<p>This program introduces students to the fundamentals of social analysis, equipping them with tools to critically examine structures of power, inequality, and change. Through interactive sessions, students learn to apply key concepts and frameworks to real-world issues. They engage with contemporary case studies on pressing social concerns in Indian society—such as caste, gender, migration, and environmental justice—developing analytical skills and ethical awareness. The program fosters reflective thinking, collaborative learning, and a deeper understanding of social dynamics. Ideal for students passionate about social impact, it empowers them to become informed, empathetic contributors to a more just and inclusive society.</p>
