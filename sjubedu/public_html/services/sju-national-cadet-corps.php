            <p>SJU has two of the oldest NCC Units of Bengaluru. The Air Wing and the Armoured Wing were started in 1954 and 1962 respectively. 
            It enrols both boys (Senior Division) and girls (Senior Wing). The cadets are trained by senior NCC Officers who are also faculty members of the University. 
            The enrolment in the NCC is always done keeping in mind the available vacancies.</p>

            <p>The cadets are trained in handling different weapons, and take part in flying, aero-modelling, firing, trekking, rock climbing, mountaineering, 
            cycling, Republic Day camp, and youth exchange programmes, apart from team building exercises.</p>

            <p>The cadets have received several commendations and awards for their outstanding performance. Many cadets complete the ‘C' certificate and get a direct entry to join the Armed forces.</p>

            <p>Ever since 1948 when the National Cadet Corps was created, its purpose was to create dynamic, young, bright citizens who would play an 
            important role in the country's future. The motto of NCC is “UNITY AND DISCIPLINE”. The aim of NCC is to inculcate qualities of a true leader: 
            positive thinking, right attitude, social concern and dignity. The uniform that a cadet wears ensures self-respect, discipline and obedience. 
            Every cadet undergoes meticulous training in order to shape a cadet as a productive citizen of the nation. Being an NCC cadet is not just a task, 
            but also an adventure of one's lifetime. In search of the best of men and women, tests are conducted. Students are chosen after successful completion of these tests. </p>

            <p>According to the NCC timetable, it is mandatory to conduct 20 parades in the first year. The regular parades are conducted under the watchful eyes of ANO. 
            The first few parades are focused on shaping a cadet. As the saying goes “A little pressure converts a lump of coal into diamonds”. 
            Every cadet undergoes rigorous training programmes in order to be transformed into diamonds.</p>

            <p>Besides regular parades, theory classes are also held so that a cadet would be familiarised with aeroplanes, rifles and so on.</p>
