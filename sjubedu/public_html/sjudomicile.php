  <div class="verify-card p-5" style="background: #f8f9fa; border-radius: 10px;"> 
    <h3 class="section-title text_blue fw-bold mb-4"> CATEGORIES OF STUDENTS</h3> 

    <div class="terms-card">
        <h5 class="text_blue fw-bold mt-4">Domicile of Karnataka</h5>
        <p class="mb-3">Refers to a resident of Karnataka for the last 7 years continuously (Resident Indian Nationals who studied in the State of Karnataka for the last 7 years in a recognised school/institution).</p>

        <h5 class="text_blue fw-bold mt-4">Non-Karnataka Students</h5>
        <p class="mb-3">Refers to Indian Nationals who are residents of other states and or pursued their education in states other than Karnataka State excluding NRI,OCI/PIO & Foriegn Nationals.</p>

        <h5 class="text_blue fw-bold mt-4">Non-Resident Indian (NRI)</h5>
        <p class="mb-2">Refers to Indian Nationals having Indian Passports and studied/studying abroad. They must have had 3 (Three) years of education in any foreign country during the last 6 (six) years and must have passed the qualifying examination or equivalent from abroad.</p>
        <p class="mb-2">A candidate who falls under any of the following classifications shall apply under the NRI student category:</p>
        <ul class="mb-3">
            <li>NRI as defined under the Indian Income Tax Law.</li>
            <li>Either of the parents is outside India on a work permit/resident permit.</li>
            <li>Indian citizen financed by any institution/agency outside India, even if parents are residents of India.</li>
        </ul>
        <p class="mb-3">Candidates who have completed their last qualifying examinations outside India (even if affiliated with CBSE or any other board or university within India) shall apply under the NRI category.</p>

        <h5 class="text_blue fw-bold mt-4">Overseas Citizen of India (OCI)</h5>
        <p class="mb-2">Refers to a Overseas Citizen of India (OCI) having an international passport and OCI card issued by the concerned Indian Mission whose parents and or grandparents are of Indian Origin.</p>
        <p class="mb-2">An Overseas Citizen of India (OCI):</p>
        <ul class="mb-2">
            <li>whose parents/grandparents were a citizen of India at the time of, or at any time after 26 <sup>th</sup> January 1950; or</li>
            <li>whose  parents/grandparents were eligible to become a citizen of India on 26 <sup>th</sup> January 1950; or</li>
            <li>whose  parents/grandparents belonged to a territory that became part of India after 15 <sup>th</sup> August 1947; or</li>
            <li>who is a child or a grandchild or a great-grandchild of such a citizen; or</li>
            <li>who is a minor child of such persons mentioned above; or</li>
            <li>who is a minor child and whose both parents are citizens of India or one of the parents is a citizen of India - is eligible for registration as an OCI cardholder.</li>
        </ul>
        <p class="mb-2">Besides, a spouse of foreign origin of a citizen of India or spouse of foreign origin of an Overseas Citizen of India Cardholder and whose marriage has been registered and subsisted for a continuous period of not less than two years immediately preceding the presentation of the application is also eligible for registration as OCI cardholder.</p>
        <p class="mb-2">However, no person, who or either of whose parents or grandparents or great grandparents is or had been a citizen of Pakistan, Bangladesh or such other country as the Central Government may, by notification in the Official Gazette, specify, shall be eligible for registration as an Overseas Citizen of India Cardholder.</p>
       <!-- <p class="mb-3"><strong>Note:</strong> 'ordinarily resident' will mean a person staying in a particular country or India for a continuous period of 6 months.</p> -->

        <h5 class="text_blue fw-bold mt-4">Person of Indian Origin (PIO)</h5>
        <p class="mb-2">Refers to a foreign citizen having an international passport with a PIO card issued by the concerned Mission, who held an Indian Passport at any point in time or whose parents/grandparents were citizens of India.</p>
        <p class="mb-2">Every person of Indian origin who is a citizen of another country, NOT being a citizen of any country that may be specified by the Government of India from time to time, will be eligible to apply for a PIO Card if:</p>
        <ul class="mb-2">
            <li>the person at any time held an Indian passport, or</li>
            <li>the person or either of his/her parents or grandparents or great grandparents was born in and was permanently resident in India, provided further that neither was at any time a citizen of any of the aforesaid excluded countries; or</li>
            <li>the person is the spouse of a citizen of India or a person of Indian origin covered under (i) or (ii) above.</li>
        </ul>
        <p class="mb-2">Presently, the specified countries whose nationals are ineligible for grant of PIO Card are Pakistan, Bangladesh, Sri Lanka, Bhutan, Afghanistan, Iran, China and Nepal. Further, if the applicant himself or either of his parents, grandparents or great-grandparents held the nationality of these specified countries at any time, he will not be granted a PIO Card.</p>
     <!--   <p class="mb-3">Iranian nationals of Indian origin can be considered for grant of PIO card. The Missions or other agencies authorised to issue PIO cards would obtain prior clearance from the Ministry of Home Affairs before issuing the card to an Iranian national.</p> -->

        <h5 class="text_blue fw-bold mt-4">SAARC Nationals</h5>
        <p class="mb-3">Refers to Foreign Nationals of Afghanistan, Bangladesh, Bhutan, Maldives, Nepal, Pakistan and Sri Lanka.</p>

        <h5 class="text_blue fw-bold mt-4">Foreign Nationals</h5>
        <p class="mb-2">Refers to all Foreign Nationals except SAARC Nationals and OCI and PIO card holders. Applicants to undergraduate/postgraduate programmes who have studied abroad or applicants who are foreign nationals should meet the following criteria:</p>
        <ul class="mb-3">
            <li>Students who have studied International Curriculum must obtain an equivalence certificate from the University Grants Commission (New Delhi). <a href="https://www.ugc.ac.in/equivalence" target="_blank">https://www.ugc.ac.in/equivalence</a></li>
            <li>Applicants pursuing an IB curriculum must have 3 HL and 3 SL with 24 credits.(IB Diploma)</li>
            <li>Applicants pursuing GCE / Edexcel must have a minimum of 3 A levels with a grade not less than C.</li>
        </ul>

        <h5 class="text_blue fw-bold mt-4">English Proficiency</h5>
        <p class="mb-2">Proof of English Proficiency is essential for a candidate who has not studied at an Institution located in an English-speaking country. School/College education should have had the English language as a medium of instruction. Such a candidate has to provide one of the following two scores. The validity of the test should be two years from the date of examination.</p>
        <ul class="mb-0">
            <li><strong>International English Language Testing System (IELTS)</strong>-Academic version- minimum score of 6.0 is required.</li>
            <li><strong>Test of English as Foreign Language (TOEFL)</strong>
                <ul>
                    <li>Paper-based TOEFL: a minimum score of 500 is required.</li>
                    <li>Computer-based TOEFL: a minimum score of 175 is required.</li>
                    <li>Internet-based TOEFL: a minimum score of 60 is required.</li>
                </ul>
            </li>
        </ul>
