                      <p>The School of Chemical Sciences comprises of the Department of Chemistry and the Department of Biochemistry. The Department of Chemistry was established in 1927, and the Department of
                      Biochemistry was started in 2020. The School offers Undergraduate, Postgraduate Chemistry (Organic and Analytical), and Ph.D. programmes in Chemistry and Undergraduate programme in Biochemistry. 
                      Together, the School has built up its reputation as one among the best in the country, in imparting quality education in the domain of Chemical sciences.</p>

                      <p>The school is proud of its richly experienced, well qualified and highly dedicated faculty. The syllabi of all the courses are carefully designed and modified periodically to help students 
                      develop analytical thinking. The implementation of RBPT (research-based pedagogical tools) and project work for PG and UG students have created great interest and creative thinking in Chemistry, 
                      putting education into action. Many of the student projects have been published in reputed journals and/or presented at National/International conferences.</p>

                      <p>The School truly stands out in research and has well-established research labs equipped with modern scientific instruments. The School is proud of having analytical facilities which include 
                      UV, IR, AAS, GC, HPLC, PXRD, IC, AFM, spectrometers, emission spectrometer, electrochemical work station, turbidimeter, rotavapors, high speed centrifuge, cold room, semi auto biochemistry 
                      analyzer and many others. The ongoing research areas include catalysis, materials chemistry, electrochemistry, organic synthesis, protein chemistry, and other areas of biochemistry as well. 
                      Our distinguished faculty have been publishing their work in reputed national and international journals of high impact factor. The total number of research articles published is over 200.
                      Over the past 25 years, the faculty have received financial assistance for their research work from local industries as well as from the Government funding bodies such as UGC, DST, SERB, CSIR 
                      and BRNS. The department has been recognized by DBT and DST and been awarded DBT- STAR status and DST-FIST funding.</p>

                      <p>The school has established research collaborations with national and international laboratories and institutes. St. Joseph's University has also established a tie-up with chemical 
                      and analytical industries and signed an MOU recently, adding strength to the department. Many alumni of the department are performing exceedingly well in the fields of academics, research 
                      and industry within India and abroad as well.</p>

                      <p>The school boasts of vibrant UG Chemical and Biochemical Societies, PG Chemical Society as well which are always abuzz with co-curricular activities such as organizing seminars 
                      and lecture programmes by eminent scientists like Prof. CNR Rao and Nobel laureate Prof. Venkatraman Ramakrishnan, inter-collegiate chemistry festivals, educational trips, science exhibitions 
                      and outreach activities.</p>

                      <p>The school aims to achieve global standards of quality in maintaining academic excellence by being proactive and open to new opportunities and challenges in frontier 
                      fields. The endeavour of the school is to prepare brilliant young chemists, who by their scientific knowledge skills, creativity, leadership and social commitment, would 
