           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2>
           </div>
          <p>The Department of Management, under the School of Business, has been training and developing future entrepreneurs since the year 2019. The Department has two major programmes namely
          the regular BBA programme and BBA Strategic Finance, a programme embedded with Certified Management Accountant (CMA) programme. The Department has ensured an industry-driven and updated
          syllabus that constantly evolves according to the present needs of the market. The faculty comprises well-qualified experts in various fields, working on various research projects to
          further their knowledge about the world of Business.</p>

          <p>The Department believes in holistic development and encourages our students to take part in various institution-level and department-level activities as well as participate in 
          intercollegiate events. An association unique to the Department, the âBusiness Association' conducts fests and competitions for the students to upskill them with practical approaches
          to problem-solving. Students are also encouraged to take part in various social service activities; they are taught to work towards the upliftment of society, working as men and women
          for others.</p>

          <p>Guest lecturers and interactions with entrepreneurs and known leaders are conducted by the Department to give students a more in-depth look at the practical working of the different
          sectors of Industries. Students are also taken on study tours and industrial visits to bring out in them the spirit of innovation and invention, through a close-up look at the production,
          and running of business organisations. The Department continuously strives towards creating better leaders and future agents of change.</p>
