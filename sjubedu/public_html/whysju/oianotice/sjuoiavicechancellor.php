                 <p>Dear International Student,</p>
<p>We invite you to join St Joseph's University, Bengaluru, and embark on a transformative higher education journey that will enrich your academic and professional future at one of India's oldest and most distinguished educational institutions, established in 1882.</p>

<p>The University is administered by the Society of Jesus (SJ), also known as the Jesuits, founded by St Ignatius of Loyola in 1540. Headquartered in Rome, the Jesuits are globally renowned for their commitment to quality education and character formation across nearly fifty countries. The Jesuits arrived in India in 1542 under the leadership of St Francis Xavier and established St Paul's College, the first higher education institution in India. Over the centuries, they founded numerous schools, colleges, and seminaries throughout the country. Many of India's premier century-old, not-for-profit institutions continue to be administered by the Jesuits, including St Joseph's College, Trichy, St. Xavier's College, Kolkatta, St Xavier's College, Mumbai, Loyola College, Chennai and St. Aloysius, Mangalore.</p>

<p>Founded as St Joseph's College in 1882, our institution has built an illustrious legacy of academic excellence spanning more than 143 years. On 2 July 2022, the Government of Karnataka elevated the college to the status of a university under the Rashtriya Uchchatar Shiksha Abhiyan (RUSA) initiative of the Ministry of Education, Government of India. St Joseph's University has the unique distinction of being the first Public-Private-Partnership (PPP) university of its kind in India.</p>

<p>On 27 September 2022, Her Excellency, Smt. Droupadi Murmu, President of India, formally inaugurated the University. The Bangalore Jesuit Educational Society has since undertaken a visionary mission to develop the University into a centre of world-class education that remains affordable and accessible to deserving students from all backgrounds, irrespective of caste, creed, economic status, or nationality. This mission is guided by the enduring values of academic excellence, character formation, and social responsibility.</p>

<p>The University is also committed to significant expansion and modernisation of its infrastructure. Plans are underway to enhance facilities at the Lalbagh Road Campus, including libraries, laboratories, computer and network systems, hostels, cafeterias, sports facilities, auditoriums, seminar halls, observatories, student wellness and counselling centres, placement and skill development cells, and more. Simultaneously, a state-of-the-art new campus is being envisioned on the 30-acre site at Mount Saint Joseph, Bannerghatta, to support the University's future growth and aspirations over the coming years.</p>

