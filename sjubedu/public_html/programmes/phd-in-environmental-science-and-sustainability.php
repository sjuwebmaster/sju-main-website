                       </header>
                        <p><strong>Admission Process : </strong>The applicants must fill in complete information on the online application form and upload all required certificates (whatever is available) and photos.</p>
                    <p><strong>Selection Process : </strong>The candidates have to appear for an entrance test. The details of the entrance test are detailed below. The shortlisted candidates will be called for an interview. The dates of the entrance test and the subsequent interview are available under the section "Important Dates" on the programme page. Once the final interview is over, candidates have to pay their programme fee within 7 days and the mode of payment must be online.</p>
                    <h6><strong>General Structure for Admission Entrance Test:</strong></h6>
                    <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>There will be an entrance test of two-hour duration, carrying 70 marks, based on which a shortlist of candidates will be prepared, followed by an interview for the shortlisted candidates, carrying 30 marks.</li>
                    </ul>
                    <h6><strong>For Environmental Science and Sustainability:</strong></h6>
                    <p>The Entrance exam will consist of MCQs for 70 marks</p>
                    <h6><strong>Note:</strong></h6>
                    <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>Candidates who have qualified NET (JRF/LS), GATE, and KSET (Karnataka) are exempted from the entrance test. They will directly attend the interview (100 marks).</li>
                       <li><i class="fas fa-check me-2"></i>The selection will be based on the combined score obtained by the candidate in the entrance test and the interview.</li>
                    </ul>
