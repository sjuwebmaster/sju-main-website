               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>This programme has been one of the most popular courses in the School of Physical Sciences over the past few years. 
               It trains students in statistics and computer science, together with the necessary mathematical background. We have observed 
               and deliberated that there are several ways the roles of statisticians, mathematicians and computer scientists merge. 
               Statistical science uses maths as one of its primary and fundamental tools, and mathematical statistics refers specifically to 
               the rigorous application of mathematical principles to the collection, interpretation, and presentation of data. The integration 
               of statistics and computer science has created a wealth of new opportunities for professionals in this field.</p>
        </article>
