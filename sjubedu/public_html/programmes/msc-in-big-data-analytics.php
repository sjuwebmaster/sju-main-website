            <p>The MSc Big Data Analytics programme is designed to equip students with advanced knowledge and practical skills required to manage, process, and analyze large-scale data for real-world decision making.
               The curriculum emphasizes Data Engineering, Advanced Analytics, and Artificial Intelligence, enabling students to build end-to-end data pipelines, work with distributed computing frameworks, and derive meaningful insights from complex datasets. With a strong focus on hands-on learning, students engage in mini-projects and industry-based case studies that address real-world challenges across domains such as healthcare, finance, retail, and smart systems. The programme also promotes research-oriented learning, encouraging students to undertake research projects, develop innovative solutions, and publish research papers in conferences.
               Additionally, the curriculum integrates industry-focused tools and technologies, including big data platforms, cloud computing, machine learning, and data visualization, ensuring students gain practical exposure aligned with current industry requirements. Through continuous mentoring, internship opportunities, and placement-focused training, the programme aims to mould students into industry-ready professionals.</p>

