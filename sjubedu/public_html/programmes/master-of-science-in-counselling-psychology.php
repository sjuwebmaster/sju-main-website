        <article id="eligibility" class="dept-section department_tab pgm-details mt-5 p-3">
             <h3 class="fw-bold text_blue mb-3"> Eligibility</h3>
            <div class="below-pg-title">
                     <ol class="eligibility-list p-0">
                       <li class="pb-3">Candidates must have completed a BA/BSc undergraduate degree with Psychology as a cognate subject, with at least 
                       50% marks in the aggregate of all subjects and 55% in the aggregate of all Psychology papers. OR </li>   
                       <li class="pb-3">At least one core paper in Psychology as part of an undergraduate degree (e.g. BEd, BSc Nursing, Bachelor's degree in Physiotherapy, 
                       Management, or Health Sciences, or Bachelors degree in Social Science subjects like Sociology, Social Work, Philosophy, or Rehabilitation Sciences), 
                       with at least 50% marks in the aggregate of all subjects and 55% in the aggregate of all Psychology papers. OR </li>  
                       <li class="pb-3">A one-year diploma in Counselling Psychology with 55% in the aggregate of all Psychology papers.</li>
                       <li class="pb-3">Candidates must pass the designated entrance exam.</li>
                     </ol>
                     <div>
                        <h5><strong>The entrance exam will have three components, listed below:</strong></h5>
                        <h6><u><strong>Component A: General psychology (40 marks)</strong></u></h6>
                        <p>Core areas of psychology, including its origins, biological and cognitive processes, social influences, and 
                        therapeutic approaches. Research methods, statistical tools, and ethical practices, alongside applications in mental 
                        health and counselling and also merging areas like positive psychology and technology.</p>
                        <h6><u><strong>Component B: Logical Reasoning (11 marks)</strong></u></h6>
                        <p>Awareness of logical and analytical thinking. Focuses on verbal reasoning (analogies, syllogisms, logical deductions), 
                        non-verbal reasoning (pattern recognition, sequencing), analytical reasoning (data interpretation, critical thinking), 
                        logical puzzles (blood relations, seating arrangements), and decision-making (case studies, situational judgement).</p>
                        <h6><u><strong>Component C: Counselling Aptitude (9 marks)</strong></u></h6>
                        <p>Essential awareness of counselling principles and empathy. </p>
                        <p>Successful candidates from the entrance exam will be required to attend an interview.</p>
                     </div>
