          <p>Established in 2016 with a flagship two-year Postgraduate program in Big Data Analytics, 
            the Department has since undergone a period of strategic expansion. In 2020, the portfolio grew to include a Bachelor of Computer Applications (BCA) in Data Analytics and a Postgraduate Diploma in Cyber Security, the latter developed in collaboration with the HKCS Foundation. This was followed in 2021 by the introduction of a specialized one-year Postgraduate Diploma in Data Analytics,
            creating a comprehensive academic ladder in emerging technologies.</p>
           <p>The M.Sc. in Big Data Analytics is distinguished by the formal patronage of Tata Consultancy Services (TCS), which includes a dedicated, 
            state-of-the-art laboratory facility. The program is academically steered by the eminent researcher</p>
         <p>Professor Bimal Kumar Roy, Padma Shri awardee and former Director of the Indian Statistical Institute (ISI). Under his guidance,
             the curriculum bridges the gap between sophisticated mathematical theory and high-level industry application.</p>
          <p>To support intensive research and instruction, the Department maintains a high-performance laboratory with a 60-seat capacity and extended operational hours. 
            The facility features a high-speed computing infrastructure optimized for massive data workloads and is equipped with a high-definition Cisco video conferencing suite. 
            This connectivity allows for seamless real-time interaction between students, faculty, and industry consultants, fostering a culture of collaborative professional development.</p>
          <p>The success of the M.Sc. program is evidenced by over 600 graduates who have successfully transitioned into leadership and technical roles within India’s premier IT firms, including TCS. 
            These alumni are currently spearheading complex initiatives in statistical modeling, Machine Learning, Deep Learning, and AI. 
            This track record of placement underscores the Department’s commitment to producing highly skilled professionals ready to address the complexities of the global digital economy.</p>
