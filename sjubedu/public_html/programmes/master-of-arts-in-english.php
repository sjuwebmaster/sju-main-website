               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>In <strong>British Literature</strong>,  the student will read texts from Old, Middle and Modern English and thus encounter Beowulf, Chaucer, Shakespeare, Aphra Behn, 
               Donne, Milton, Wordsworth, Eliot, Auden, Virginia Woolf, Carol Ann Duffy, Zadie Smith and Daljit Nagra over four semesters.</p>

               <p><strong>Indian Literatures</strong> justifies its plural title by traversing the several different conversations that we know by names such as Indian Writing in English, 
               Modern Indian Literatures in Translation, Dalit and Bahujan Writing, Indigenous Narratives, and Minority Literatures in India. Contemporary debates and issues 
               will be discussed extensively.</p>
               <p><strong>English Studies</strong> will take the learner on a sojourn through the notions of literary criticism and literary theory, while offering conversations about 
               aesthetics, gender, exclusion, canon-formation, decolonisation, and popular culture. </p>
               <p><strong>Electives</strong> are offered in <strong>Linguistics</strong> and <strong>World Literature</strong> a. Those doing Linguistics will first finish a two-semester course in General Linguistics 
               before taking up papers in Sociolinguistics, and Stylistic Analysis.</p>
               <p><strong>World Literature</strong> students will read fiction and poetry from several regions, starting with Europe, the Americas, Africa and the Caribbean, 
               and culminating in South and East Asia.</p>
               <p>MA students will also receive training in <strong>Creative Writing</strong> and <strong>Theatre Skills</strong> over the two years of the programme.</p>
               
               <h4>Course Experience</h4><hr>
               <p>The student will write a research paper every semester, participate in public communication exercises, learn to work with new research tools and approaches, 
               publish and present their research/ creative work, and undertake translation projects in addition to putting together festivals of literature and film and 
               organising national and international conferences.</p>
               <p>Writers who have interacted with our students over the last few years include Mridula Koshy, Nisha Susan, C.K. Meena, Anjum Hasan, Perumal Murugan, 
               Ramachandra Guha, Amandeep Sandhu, Vasudhendra, Sukirtharani, Sujatha Gidla, and Joe Sacco.</p>
