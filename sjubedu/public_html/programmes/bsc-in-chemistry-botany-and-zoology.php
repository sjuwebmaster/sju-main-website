               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>This programme takes into consideration that since animals and plants co-evolve in every environment, it's impossible to focus on one science without drawing from 
               the other, and the basic building blocks of animals and plants can be studied only with the help of chemistry. Therefore, the study of one discipline will customarily 
               reference the other for a better understanding of the natural world. Another significance of this course is that these two seemingly different branches of science are 
               often found crossing paths in medical research. Both chemistry and botany are commonly studied areas of science when researchers are seeking to understand and cure 
               disease.</p>

               <p>The Dept of Chemistry aims to achieve global standards of quality in maintaining academic excellence by being proactive and open to new opportunities and 
               challenges in the frontiers of chemistry. The Dept of Botany promotes a culture of academics and research amongst its students. The Faculty of Zoology unites 
               the disciplines of General Zoology, Cell Biology and Genetics, Human Anatomy- Physiology, Developmental Biology, Ecology, Ethology and Evolutionary Biology.</p>
        </article>
