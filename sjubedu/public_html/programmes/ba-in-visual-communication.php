             <h3 class="fw-bold text_blue mb-3"> Eligibility</h3>
            <div class="below-pg-title">
                     <ol class="eligibility-list p-0">
                       <li class="pb-3">A candidate who has passed the two-year Pre-University Examination conducted by the Karnataka Pre-University Education Board 
                       or any other examination considered equivalent the Government of Karnataka shall be eligible for admission to this programme.</li>
                       <li class="pb-3">In addition to the above criteria, admissions to UG programmes in the School of Communication and Media Studies will be determined 
                       through an assessment consisting of a test, interviews, and portfolio assessment. The total marks allocated for the assessment will not exceed 50.</li>
                       <li class="pb-3">These criteria may be subject to change based on the modality or platform used for the Entrance Test.</li>
                       <li class="pb-3">Students of undergraduate programmes must study two languages, out of which one shall be English and the other shall be either an 
                       Indian language or a foreign language other than English.</li>
                     </ol>
                       
                     <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>The University offers the following language courses: Introductory Kannada, 
                       Introductory French, Introductory Spanish, Kannada, Hindi, Tamil, Sanskrit, French, Additional English and German.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>CBSE and ISC students and others who have not studied a second language at the plus two level are 
                       encouraged to opt for Introductory Kannada, Introductory French, Introductory Spanish or German. These are taught from the introductory level and 
                       require no prior acquaintance. Only those students who have not learnt these languages either in school or class XI or XII are eligible to enroll 
                       for these introductory level courses as second language.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>Students need PUC/XII level competence to study Sanskrit, Kannada, Tamil, Hindi and French courses.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>Additional English is meant for students who have serious problems learning other languages.</li>
                     </ul>
