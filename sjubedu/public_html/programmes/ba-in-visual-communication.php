               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>The Bachelor of Arts in Visual Communication (BVC) programme equips students to be content creators to work with audiences through various platforms 
               such as websites, television, visual media, and print. Students who pursue this programme develop skills concerning various aspects of the visual medium 
               such as photography, film, sound, design fundamentals, digital media design, technical communication, drawing techniques, visual literacy, design history, 
               web design, colour management, branding, etc. There are plenty of job opportunities available to students who complete their Visual Communication degree. 
               Most students of Visual Communication find employment in the advertising, photography, fashion, design, publication, and marketing Industries.</p>
        </article>
