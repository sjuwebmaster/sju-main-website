               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>This programme integrates various social sciences that examine human behaviour, social patterns, and structures. It investigates the 
               intricate relationships among these distinct aspects of human society, emphasising their unique characteristics, areas of intersection, 
               and the importance of their contributions to our comprehension of the social world. Furthermore, it combines the chronological account 
               of historical events and developments with the facts that have influenced the nature and functioning of state systems and governments 
               across different nations. Sociologists frequently draw upon historical context to elucidate social changes, developments, and the evolving 
               dynamics of society over time; thus, the course underscores the significant interplay between these two domains.</p>
        </article>
