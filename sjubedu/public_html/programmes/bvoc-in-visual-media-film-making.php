               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>The BVoc Visual Media and Filmmaking (VMF) is a three-year comprehensive degree programme that lays a foundation for all aspects of filmmaking for the student. 
               Blended with a modern and updated pedagogical approach to the teaching-learning process, the programme provides a congruence between students' holistic development 
               and industry suitability. The programme has state-of-the-art film studios, rich internships, film clubs, film festivals, workshops, hands-on training and master classes.</p>
        </article>
