            <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
          <p>The B.Voc. in Filmmaking and Content Creation is a three-year vocational degree programme designed to develop creative, technical and professional skills for film, television and digital content industries. The programme combines the study of cinema, visual communication and storytelling with hands-on training in photography, screenwriting, cinematography, editing, sound, direction and production.
          The programme progresses from foundational skills in visual design, writing, photography and communication to specialised learning in film production, lighting, sound design, visual effects, motion graphics, documentary filmmaking, art direction and production management. Students also explore world and Indian cinema, film theories, emerging media practices, new media skills, social media management, film distribution, media law and ethics, and film preservation and restoration.
          Practical learning is central to the programme. Students develop production skills through studio and location-based exercises, screenplay and audiovisual projects, and a final film project. Pre-production planning and an internship provide opportunities to apply their learning in professional contexts and build a portfolio of creative work.
          Graduates can explore careers in filmmaking, video production, television, digital media and content creation. Potential roles include assistant director, cinematographer, film and video editor, screenwriter, sound designer, production coordinator, documentary filmmaker, social media content creator and digital video producer. They may work with production houses, television channels, advertising and digital agencies, media organisations, or pursue freelance work and entrepreneurship.
          </p>
