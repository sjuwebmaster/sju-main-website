						<ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>Candidates who have qualified NET (JRF/LS), GATE, and KSET (Karnataka) are exempted from the entrance test. They will directly attend the interview (100 marks).</li>
