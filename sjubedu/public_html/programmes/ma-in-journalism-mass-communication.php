               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>MA Journalism and Mass Communication (MA - MCJ) is a two-year intensive programme offering THREE SPECIALISATIONS (from the 2024 batch):</p>
               <ol class="ps-3">
                 <li class="pb-2">Advertising and PR / Corporate Communications</li>
                 <li class="pb-2">Multimedia Journalism, Content Production, and Design</li>
                 <li class="pb-2">Visual Storytelling on Film and Television platforms, including digital media</li>
               </ol>

               <p>This specialising program offers a wide range of courses in the Mass Communication domain. The programme offers a myriad of options 
               for career choices in the field. Underpinned by the latest pedagogical practices of discussions, industry interactions, and research, 
               this programme aims to develop a holistic environment for students to inculcate the best industry and academic practices, and be equipped with suitable career opportunities.</p>
        </article>
