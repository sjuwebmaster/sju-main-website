               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>The Dept of Economics is committed to generating interest in the discipline of Economics among students by imparting sound theoretical 
               knowledge and developing quantitative skills to analyse economic behaviour. The Dept of Statistics is committed to equipping students to 
               become practising Statisticians by providing them with a platform to analyse real-life data, draw conclusions, and support conclusions by 
               explaining the reasoning behind them. The Dept of Maths initiates students to the power of abstraction, to enjoy and create patterns and 
               explore relationships that underlie mathematical structures.</p>
