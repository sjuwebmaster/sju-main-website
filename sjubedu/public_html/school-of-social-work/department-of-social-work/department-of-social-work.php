           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p> The School of Social Work at St Joseph's University, Bengaluru, established in 2005, is committed to nurturing social change agents who seek to improve 
          the quality of life for marginalized and vulnerable communities. The School offers rigorous Bachelor of Social Work (BSW), Master of Social Work (MSW) and 
          PhD programs designed to equip students and scholars with the knowledge, skills, and ethical grounding essential for effective social work practice.</p>

          <p> The BSW program lays a strong foundation by preparing graduates to address the complex social problems of today through critical self-reflection, 
          applied theories, and field work. It fosters an understanding of social justice, human rights, and the need for intervention at individual, family, 
          group, and community levels. The curriculum is built to develop socially sensitive professionals capable of advocating for systemic change. Freshly 
          graduated adolescents are enrolled in this program and are trained on life skills to know oneself better.</p>

          <p> Building on this foundation, the MSW program offers an integrated curriculum that intertwines classroom learning with extensive fieldwork. 
          This blend ensures that students gain hands-on experience while deepening their theoretical knowledge. A well-trained faculty supports students 
          through research and practical guidance to develop competencies that empower them to lead innovative social work interventions. The program emphasizes 
          an intellectual, scientific, and action-based approach to social transformation.</p>

          <p> Each semester includes placements such as concurrent and block fieldwork, rural camp, community visits, and specialized projects, providing students 
          with real-world exposure that prepares them to be catalysts of change. Through this experiential learning, students develop empathy, professional ethics, 
          and leadership qualities essential for social workers.</p>
