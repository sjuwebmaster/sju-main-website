           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Physics department at St. Joseph's College had its humble beginnings in the year 1923 under the first HOD Sri. S. Ramaswamy Iyengar and 
          Sri. P. Devasy. At present, the Department has 14 faculty members and teaching around five hundred students in the UG section and 60 students 
          in the PG programme. Over the last nine decades, the Department has scaled new heights in setting standards of education by promoting scientific 
          temperament and kindling curiosity in physics among students. The laboratories and library are enriched by grants from the UGC, K.Kasturirangan MP LADS funds, and CE grants.</p>

          <p>The department organises a certificate course âSpace and Rocket Dynamicsâ in collaboration with ISRO since 2000. The course which is also open to 
          students from other institutions provides a unique platform for the engineering and degree students to interact closely with eminent scientists from ISRO, 
          and IIA. The course helps in creating awareness among the students on India's triumphant odyssey in space exploration. The department has to its credit an 
          8-inch Schmidt-Cassegrain optical telescope sponsored by ISRO to see the wonders of the night sky.</p>

          <p>Some of the courses are provided through learning management systems. The numerical techniques course has a hand on laboratory using Python programming. 
          There are two open electives 1. Astrophysics 2. Material Science. The students will have to do a compulsory project with premier research institutes like ISRO, IISc, 
          RRI and IIA, etc during their final semester. In addition, the programme has initiated bridge courses to make learning physics at the PG level more conformable and 
          provide continuity to the narrative from the UG curriculum and help students from disparate backgrounds. A recent approval of the department as a Research Centre 
          under Bangalore University will see more advances in the unique features of this department.</p>
