        <article id="about" class="dept-section department_tab">
           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department of Electronics was established in 1984 and the programme Physics, Mathematics and Electronics (PME) became a Grant-in-Aid programme in 1988. 
          The Department offers undergraduate programmes in Electronics. With a legacy of thirty-eight years, our mission is to develop young men and women with active and 
          creative minds, inculcating a scientific temper in them. We try to achieve this by exposing them to theories and applications of Electronic Science that are in 
          tandem with the latest technological developments.</p>

         <p>We update our syllabus according to the latest trends in the industry and the trends in highly interdisciplinary research going between Electronics and other subjects. 
         The Department has been recognised by DBT through the award of DBT-STAR college status in 2019. We wish to help our students expand the horizons of their understanding 
         concerning the revolutionary contribution of Electronics to human well-being and also to facilitate the actualisation of their rich potential for unique contributions 
         to life-enhancing technology. During the course of their study, the students learn about various topics under Electronics, like Analog Electronics, Digital Electronics, 
         Sensors, Communication Electronics, Microprocessors and Microcontrollers. To give an edge to the students we have incorporated hardware description language and other 
         relevant software in the syllabus. The students get hands-on expertise and prepare interesting circuits and projects during their course of study. The Department 
         comprises a versatile and experienced faculty. The spacious laboratories are well equipped with the latest devices and instruments.</p>

         <p>The Department provides a platform for students to indulge in electronics-related activities both at intra-collegiate and intercollegiate levels through 
         its academic club named JET club. This helps in the team building and holistic development of young minds. The Department organises its popular Annual Inter-College 
         Fest ‘SHOCK’ every year.</p>
         <p>We offer an inclusive, supportive and academically challenging learning environment. With personal attention and mentoring from faculty and collaborative hands-on projects, 
         students are inspired to excel and innovate.</p>
