           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p> The Department of Mathematics was established in 1923. It is one of the oldest science departments in the Institution. 
          The Department offers undergraduate and postgraduate programmes. In 2014, the Department instituted the MSc Mathematics programme 
          to promote higher studies and research in Mathematics. At present, the Department has 18 well-qualified and highly dedicated faculty 
          members and teaches over 800 students in the UG section and over 80 students in the PG programmes. The Department provides a platform 
          for students to indulge in Mathematics-related activities at both intra-collegiate and intercollegiate levels through its academic club 
          named ABACUS. The good work of the Department has been recognised by DBT and DST through the award of DBT- STAR and DST-FIST funding.</p>

        <p> The Department endeavours to be a centre of excellence nurturing joyful curiosity in learning, enthusiastic creativity in research, and passion 
        for building a respectful, free, transparent, and dynamic pedagogic community. The Department enthusiastically initiates students to the power of abstraction. 
        Students are led to enjoy and create patterns and explore relationships that underlie mathematical structures. The learning process is conducted in a manner 
        that interests students and opens their minds to explorations in the subject.</p>
