        <article id="about" class="dept-section department_tab">
           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>We live in a world where the use of statistical data is pivotal to comprehending many issues around us. The Department of Statistics 
          in St Joseph’s College was established in 2010. The Department of Statistics is committed to excellence in teaching and equipping students 
          to become practicing Statisticians. The Department provides a platform for the students to analyze real-life data, draw conclusions, and 
          support conclusions by explaining the reasoning behind them. The Department also offers two certificate courses namely “Statistics using 
          SPSS and MS Excel” and “Data Science and Analytics”. The programme also includes internships and projects with analysis of real-life data. 
          The main objectives of the department are to acquaint students with various statistical methods and their application in different fields, 
          cultivate statistical thinking among students, develop skills in handling complex problems in data analysis and research design, and prepare 
          students for future courses having quantitative components.</p>

          <p>The department aims to instill scientific temper, analytical skills, and intellectual vigor among students, so that they may contribute 
          to the needs of society. The department aims to provide students with life-oriented education through projects of social relevance. The department 
          is offering eight papers in six semesters for the students. These papers introduce basic statistical tools needed for postgraduate study in 
          statistics/applied statistics. These papers are designed to impart the learning of statistical methods and tools, which is expected to improve 
          students’ ability to analyse various types of real-life data. Introduction to Probability and Statistics and theoretical probability distributions 
          are papers that help students to acquire basic knowledge in statistics, understand the importance of statistics, and will provide students with 
          basic knowledge of probability models and their applications in real-life problems. The papers Statistical Inference- I and Statistical 
          Inference -II provide basic knowledge of estimation theory.</p>
