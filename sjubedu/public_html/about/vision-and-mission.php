                       <li class="pb-3"><strong>Reflection -  </strong>A foundational value of Jesuit education is the practice of reflection. Students are invited to pause and consider the world 
                       around them and their place within it, before making decisions. This includes challenging the status quo, acknowledging biases and accepting responsibility for action;</li>

                       <li class="pb-3"><strong>Service rooted in justice and love -  </strong>Jesuit education cultivates critical awareness of social and personal evil, but points out that 
                       God' s love is more powerful. This value is illustrated through community service programs, immersion experiences, and various volunteering opportunities for students;</li>

                       <li class="pb-3"><strong>Solidarity and kinship – </strong>Students work together for the greater good. They develop relationships with their surrounding communities 
