          <article class=" mt-5 mb-2"> 
                  <p>In 1882, St. Joseph's College (SJC) had its significant beginnings with the French Foreign Mission fathers, who were mandated to start a 
                  catholic institution to cater to the catholic community that comprised about 1000 Europeans and 5000 Indians. In 1904, the European and Indian 
                  sections separated and until 1949, the institution remained affiliated to the Madras University. As a constituent of Madras University, it was 
                  granted the status of a first-grade College in 1926. The landmark year was 1937, for during this year the French Mission Fathers handed over its 
                  administration to the Society of Jesus (Jesuits). In 1949, the institution was affiliated to the Mysore University. In 1967, the institution was 
                  granted affiliation to Bangalore University. From 2018, the institution is affiliated to Bengaluru City University.  St Joseph's University is the 
                  upgradation of St. Joseph's College (Autonomous) under RUSA 2.0. In February 2021, St Joseph's University bill was presented in the 
                  Karnataka Legislative Assembly and was subsequently passed by the Legislative Assembly and Karnataka Legislative Councill. The college received its 
                  University status on 2 July 2022 and was inaugurated as India's first Public-Private-Parnership University by the Honourable President of India, 
                  Smt. Droupadi Murmu on 27 September 2022.</p>
