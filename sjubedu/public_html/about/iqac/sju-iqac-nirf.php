  <script>
    (function () {
      var btns = document.querySelectorAll('.nl-filter-btn');
      var cards = document.querySelectorAll('.nl-card');
      var noResults = document.getElementById('nirf-no-results');
      var countEl = document.getElementById('nirf-count');

      btns.forEach(function (btn) {
        btn.addEventListener('click', function () {
          btns.forEach(function (b) { b.classList.remove('active'); });
          btn.classList.add('active');

          var year = btn.getAttribute('data-year');
          var visible = 0;

          cards.forEach(function (card) {
            var match = year === 'all' || card.getAttribute('data-year') === year;
            card.style.display = match ? '' : 'none';
            if (match) visible++;
          });

          noResults.style.display = visible === 0 ? '' : 'none';
          countEl.textContent = visible + (visible === 1 ? ' Report' : ' Reports');
        });
      });
    })();
  </script>
