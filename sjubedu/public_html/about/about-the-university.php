    </div>
    
    <p class="text-muted">
      St Joseph's University (SJU) is a Jesuit university at the heart of Bengaluru, the Silicon city of India. Established in 1882 by Paris foreign Fathers, 
      the management of the college was handed over to the Jesuit order (Society of Jesus) in 1937. The college was first affiliated to the university of Madras 
      and later to the Mysore and Bangalore universities. In 1986, St Joseph's College became the first affiliated college in Karnataka to offer postgraduate courses. 
      In 1988, it became the first college in Karnataka to get a research center and in 2005, it was one of five colleges in Karnataka that was awarded academic autonomy. 
      In February 2021, St Joseph's University bill was presented in the Karnataka Legislative Assembly and was subsequently passed by the Legislative Assembly and Karnataka 
      Legislative Councill. The college received its University status on 2nd July 2022 and was inaugurated as India's first public-private university by the President of India, 
      Smt. Droupadi Murmu on 27 September 2022.
    </p> 
