              The emblem of an institution is the central representation of the core values which it stands for. Envisioned by the French Foreign Missionary Fathers in 1882, 
              the emblem and motto announce these core values of the institution.
          </p>

          <p>The emblem is made up of two scrolls, one scroll is placed above the crown, on which is inscribed the motto of the Institution in Latin - <span class="highlight">"Fide et Labore" </span>
             which translated to "Faith and Toil" and on the other scroll is placed beneath the palm leaves which bear the name of the Institution. 
             The shield which bears a cross in the centre is symbolic of Christian faith. There are two bees on either side of the lower part of the cross 
             representing hard and persevering work. The crown, which is placed above the shield, is a heraldic symbol of supremacy and glory. 
             The compartment beneath the shield consists of palm leaves that are a sign of victory.
          </p>

