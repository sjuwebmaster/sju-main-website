        <article id="about" class="dept-section department_tab">
           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department of French, established in 1882 by the Jesuits (originally from France) has been offering French as a second language option to undergraduate students 
          right from the start. Since 2012, French has been offered at the beginner level (A1- I and II semesters) and at the intermediate levels (A2 – III and IV semesters) 
          corresponding with the FLE (French as Foreign Language) syllabus framed under the guidelines of ‘Common European Framework of Reference’ for languages (CEFR).</p>

          <p>For students interested in exploring a different culture, the French language is the ideal choice as it helps them not only learn a new language but also get a 
          glimpse of French music, literature, cuisine, and cinema. The objective of the Department is to help students to understand basic information, questions about 
          shopping/immediate environment and successfully communicate about simple tasks, familiar topics, and matters of immediate need. On completing four semesters, 
          students traveling to a Francophone country for higher studies or professional purposes will be able to cope with basic repetitive tasks like navigating a menu 
          in a restaurant, booking a hotel, writing a short e-mail, filling out application forms, etc.</p> 
