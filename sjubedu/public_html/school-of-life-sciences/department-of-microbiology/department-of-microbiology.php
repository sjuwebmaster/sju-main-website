                     <p>At the School of Life Sciences, St Joseph's University, we believe in the power of asking questions. Questions that stem from observing and pondering about the world around us, questions about biomolecules and ecosystems, questions that continue to nurture curiosity, imagination, and a spirit of exploration.</p>

 <p>Our mission is to spark a lasting interest and joy in learning, discovery and research, while equipping students with the skills and confidence to excel in academia, industry, and society. We strive to create an environment that is intellectually engaging, collaborative, and supportive - one that helps every student to continue asking interesting questions, and forge meaningful paths.</p>

 <p>The School of Life Sciences is an interdisciplinary centre focusing on fundamental biology and applied fields. It comprises the Departments of Botany, Zoology, Environmental Science, Microbiology, Biotechnology, Food Science and Technology, and Biology. The School offers highly ranked graduate and postgraduate programs deeply rooted in scientific and rational pedagogical approaches.</p>

 <p>Learning at the School of Life Sciences extends far beyond classroom lectures and textbooks. Our faculty are trained in research-based pedagogical approaches, and ensure that the learning experience is holistic and relevant. Our programs are designed with a strong emphasis on experiential learning: hands-on practical training, interactive lectures, field-based learning, research-driven projects, regular expert lectures and workshops, and visits to academic and industry labs. Our students participate in International and national level programs like the prestigious DBT-Khorana Program, the Science Academies' Summer Fellowship program, and other fellowships and programs offered by premier research institutions in the country. Combined with the experience gained in our laboratories, these opportunities ensure our graduates are well-prepared to meet the demands of both professional and academic careers.
</p>
 <p>The School also harbours a vibrant research community-from undergraduate through graduate levels- dedicated to fundamental and socially relevant research in life sciences. Our alumni are placed in significant positions in the industry and academia, and make impactful contributions in various spheres, while also sustaining engagement with our programs at the School of Life Sciences.</p>
