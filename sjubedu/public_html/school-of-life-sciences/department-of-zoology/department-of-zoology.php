           </div>
          <p>The Department of Zoology ever since its inception in 1957 was actively involved in teaching Zoology for undergraduate degree programmes in combination with other disciplines viz., Chemistry, Botany, Zoology (CBZ); Microbiology, Chemistry, Zoology (MCZ); Chemistry, Environmental Science, Zoology (CEZ), Chemistry, Zoology, Biotechnology (CZBT) and Biochemistry, Botany and Zoology (BBZ). Now the Department offers Zoology in combination with Botany, Biochemistry, and Chemistry. The Faculty unites the disciplines of General Zoology, Cell Biology and Genetics, Human Anatomy- Physiology, Developmental Biology, Ecology, Ethology, and Evolutionary Biology. The Zoology Department has several excellent teaching facilities including well-equipped laboratories with instruments like thermal cycler, Insect culture facilities, and a Museum of specimens. The Department has ten faculty, two Associates, and eight Assistant professors. All courses are taught by lecture and practical work.
</p>
