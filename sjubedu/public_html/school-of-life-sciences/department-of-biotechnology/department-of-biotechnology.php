           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2>
           </div>
          <p>If you want to discover what Biotechnology is all about, you are at the right place. We at St Joseph's have established state-of-the-art laboratories, supported by a strong curriculum. Our students are offered organised lectures, innovatively designed practical sessions, interesting lesson plans, self-learning activities, science-based co-curricular activities, credit courses, workshops, and International collaborative courses. All in all, this makes Biotechnology learning fun and helps our students integrate this into future careers.  We have come 20 years since inception and have been funded by the DBT (Dept. of Biotechnology, Government of India) Star College scheme since 2014 and have been elevated to Star College Status grants in 2018. The Department is also funded by the Govt of Karnataka Vision Group for Science and Technology (VGST) through the Centre of Innovation in Science, Engineering and Education (CISEE) Grant's project to augment science teaching at the undergraduate level. The laboratory is well equipped to conduct research in microbial screening and identification, plant phytochemistry, plant tissue culture, molecular marker technology, Drosophila-based assays and Bioinformatics. Our staff are highly accomplished and dedicated in supporting our students' learning needs. We strongly believe in focusing our students on target-oriented learning outcomes. Our postgraduate programme has an exclusive curriculum. If your dream is to fulfil a journey from an undergraduate to a postgraduate Biotechnologist, we would love to have you here.</p>
