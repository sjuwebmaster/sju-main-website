           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2>
           </div>
          <p>Plants are an integral part of human life as they provide food, shelter, health and wealth besides oxygen. Botany is one of the fundamental disciplines of science dealing with the study of plant life. It is also the key to the development of biofuels such as biomass and methane gas that are used as alternatives to fossil fuels. It is important in the area of economic productivity of the nation, as it is involved in the study of crops and ideal growing techniques that help farmers increase crop yield. The study of plants is also important in the conservation of nature and natural resources, which has become crucial, especially on account of global warming and climate change. There is a paradigm shift in the approach of this branch. There is a shift from a qualitative approach to a quantitative approach. The Botany syllabi of both UG and PG programmes have been developed, keeping in mind the needs of the environment, society and also industry. The syllabi are constantly updated and upgraded by introducing modern techniques and recent advancements.</p>

<p>The Department of Botany was established in 1954 and it was once headed by the towering botanist, Late Rev Fr Dr Cecil J Saldanha, whose achievements have inspired hundreds of students and continue to be a guiding light to the Department and the Institution to this day. Since 2021, following the introduction of NEP, the Department Of Botany has been offering five UG programmes and one PG programme. Now the Department also offers a PhD. It is mandatory for all the postgraduate students to work on a short-term project in the second year (3rd and 4th semesters). Advanced Plant Physiology, Plant Tissue Culture, Plant Systematics and Microbiology are the fields of specialisation offered to the students. The PG programme also includes an educational plant collection tour each year.</p>

<p>The Department of Botany promotes a culture of academics and research amongst its students. Keeping this in mind, students are encouraged to take up various research topics of their interest and present their work at National and International conferences and publish papers as well. The Research Centre is also actively involved in guiding students for their doctoral degrees.  Some of the present staff are recognised research guides. The staff who retired in the recent past are also involved in guiding students for their MPhil and PhD. Over 32 PhD degrees have been awarded under the guidance of the Botany staff.</p>

<p>It has been the tradition of the Department of Botany to organise seminars, workshops, conferences and knowledge-sharing platforms throughout the year. An International Conference on âGreen Technologies for Sustainable Ecosystems and Trade Showâ was organised by the Department of Botany on 26th and 27th, February 2016 in association with Hong Kong University, Durham University, UK, Ministry of External Affairs, Ministry of Petroleum and Natural Gas, Govt of India, Ministry of Environment and Forests, Govt. of Karnataka and UGC. The Department also organised an International Conference on Cancer and Genetics, on 26-27 February 2021 in association with Agarwal Hospitals, Bengaluru.</p>

<p>The Department publishes an International Open Access Journal âBiovistas- International Journal of Biological Research (IJBR)â, ISSN -2321-0524 . Botanical Society and Centre for Molecular and Computational Biology are the two dynamic associations of the Department. Botany laboratories are equipped with major instruments for research â PCR machine, GEL doc, stereo zoom microscope, binocular phase contrast microscope with photomicrographic attachment, UV-VIS spectrophotometer etc along with a well-established plant tissue culture lab and taxonomy lab. Web-based interactive smart classes for theory and practicals are conducted along the traditional chalk and talk method. Stereo zoom microscopes with luminous focusing system interfaced with LCD projectors and binocular microscopes with built-in cameras are available to enable students for in-depth observations and photography.</p>

<p>Plant taxonomy practical sessions are conducted through an online connection to the JCB Herbarium (<a href="http://flora-peninsula-indica.ces.iisc.ac.in/">http://flora-peninsula-indica.ces.iisc.ac.in</a>) of the Indian Institute of Science, which is a digital herbarium based on the monumental work of Dr Cecil J Saldanha's âKarnataka flora''. The Department maintains a greenhouse for research purposes. Currently, funds from Research Projects (from various funding agencies), and College of Excellence (CE) Grants have been used to procure a few instruments and renovate some labs. The Department is also funded by DBT for Star College Status. Since 2017, the Department has also been receiving grants from FIST. </p>
