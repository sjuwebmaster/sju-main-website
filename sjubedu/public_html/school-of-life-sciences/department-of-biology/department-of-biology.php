           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2>
           </div>
          <p>The Department of Biology is a brand new Department formed on 21 May 2024 under the School of Life Sciences. Programmes in Biology were introduced in 2022 with the implementation of NEP but the Department itself was constituted in 2024. The Department comprises PhD qualified faculty members with expertise in both Botany and Zoology.</p>
<p>
The proposal to form the Department was put forward in November 2023 considering that Biology is at the heart of some of the biggest challenges facing humanity and our planet. From improving human health to tackling climate change, and enhancing agriculture to conserving the environment, biologists play an important role. Biology, being the science of all life and a vast eclectic science, was also found to be a necessary course due to its interdisciplinary nature. A major in Biology combines courses from Botany and Zoology to provide a strong foundation in biological principles with the flexibility to explore a variety of topics.</p>
