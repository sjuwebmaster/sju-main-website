               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>The programme is designed to provide a basic understanding of Management education, train students in communication skills effectively, and 
                    inculcate entrepreneurship skills and decision-making capabilities. The programme also includes practical exposure in the form of case studies, projects, presentations, 
                    industrial visits, and interaction with experts from the industry. It facilitates students to acquire adequate knowledge in the field of Business Administration.</p>
                    <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>The BBA programme aims at developing a student’s intellectual ability, executive personality, and management skills through an appropriate blending of business and general education.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To make sustained efforts for the holistic development of the students and thereby empower them to ably face the challenges posed by changing business environment</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>The programme also seeks to prepare students to be job-ready or drive entrepreneurship initiatives or higher education in business at home and abroad.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To inculcate a spirit of ethics and social commitment in the personal and professional life of management graduates so that they add value to society.</li>
                     </ul>
