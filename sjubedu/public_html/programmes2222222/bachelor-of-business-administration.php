                     <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>The University offers the following language courses: Introductory Kannada, Introductory French, Introductory Spanish, Kannada, 
