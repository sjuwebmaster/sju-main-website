                       <li class="pb-3"><i class="fas fa-check me-2"></i>CBSE and ISC students and others who have not studied a second language at the plus two level are encouraged to opt for 
                       Introductory Kannada, Introductory French, Introductory Spanish or German. These are taught from the introductory level and require no prior acquaintance. Only those students 
                       who have not learnt these languages either in school or class XI or XII are eligible to enroll for these introductory level courses as second language.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>Students need PUC/XII level competence to study Sanskrit, Kannada, Tamil, Hindi and French courses.</li>
