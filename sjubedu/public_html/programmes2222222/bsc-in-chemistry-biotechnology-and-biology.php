               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>One of the disciplines required for understanding Biotechnology is Chemistry. The Dept of Chemistry aims to achieve global standards of quality in maintaining 
               academic excellence by being proactive and open to new opportunities and challenges in the frontiers of chemistry. Biotechnology uses biology to solve problems and 
               make useful products, this course has been formulated. The Dept of Biotechnology has a robust curriculum with well-designed practical sessions to complement 
               theoretical concepts. The study of Biology enhances our understanding of its interdisciplinary connections with other fields of study.</p>
