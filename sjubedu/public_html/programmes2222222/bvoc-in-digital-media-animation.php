               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>BVoc Digital Media & Animation (DMA) is a three-year vocational degree programme that trains and equips students to be animators and designers of games, 
               immersive media technologies, and digital and traditional art. The students get exposure to the best hands in academia and the industry and hone their skills 
               in accordance with the needs of the industry by the time they graduate. A semester-long internship programme is a highlight of the experiential learning method 
               followed in the pedagogical approach. The students are introduced to various techniques and technology related to Augmented Reality, Virtual Reality, Character 
               Design, 2D and 3D Animation, etc. The industry connections, state-of-the-art laboratory facilities, and experienced faculty give the students an opportunity to 
               interact with the best and the latest technologies and ideas while various festivals give the students a chance to experiment with and showcase their creativity.</p>
        </article>
