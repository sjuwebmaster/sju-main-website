               <h3 class="fw-bold text-blue mb-3">Programme Details</h3>
               <p>The Ph.D. Biotechnology Program at School of Life Sciences, St Josephs’ University, Bangalore will be segmented into five stages over a maximum period of Four years (which can be amended based on the performance of the candidate and the university research committee approval), Course Work, Research Proposal Registration, Research Work, Submission of Research Work, Research Work, Defence of Thesis, each with a distinct milestone to monitor student’s progress and pursue their research at the best pace to complete their degree requirements in stipulated time. There would be an initial course work for the first year of the course which is compulsory and it is also needed that the student should pass this course work exam for the continuation of the course. The course is designed to train and cater advanced research in various areas of Biotechnology. The students are further expected to design, conduct experiments, publish research papers in Clarivate analytics suggested journals. A minimum of two research papers in these high cited journals is a mandate for  approval of thesis as per the UGC regulations. The students are also expected to present research progress at intervals to the PhD Monitoring Committee and the Doctoral committee and attend these Biannual progress meetings. The students are also expected to attend PhD colloquiums, present papers in Conferences, attend workshops during the tenure. Other research guidelines will be provided by University research office through university website post the admission into the course.</p>
