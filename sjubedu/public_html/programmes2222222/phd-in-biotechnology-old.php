             <h3 class="fw-bold text_blue mb-3"> Eligibility</h3>
            <div class="below-pg-title">
				
				<p><b>Eligibility for joining the PhD in Biotechnology:</b> Any student with a 2-year postgraduate degree with a 3 or 4-year bachelor's degree awarded in Biotechnology or  1-year postgraduate degree with a 4-year bachelor’s degree in Biotechnology or an equivalent degree with an aggregate of 55% marks/equivalent CGPA. In the case of SC/ST students, the percentage is relaxed to 50%.</p>

<p>Any student who has a 2 Year post graduate degree with 3 or 4 Year bachelor's degree awarded in any branch of Life Sciences or 1 Year post graduate degree with 4 Year Bachelor’s degree in any branch of Life Sciences or an equivalent degree in with an aggregate of 55% marks/equivalent CGPA in any branch of Life Sciences such as Virology, Nanobiotechnology, Molecular Biology, Genetics, Bioinformatics, etc.,</p>
				
			Students without NET/JRF are required to clear the entrance examination. Students with NET/JRF can directly apply for an interview.	
                     
