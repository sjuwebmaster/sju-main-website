        <article id="about" class="dept-section department_tab">
           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department was founded in 1986, offering BSc in Computer Science along with Physics and Mathematics. Continuous programmes were developed and 
          administered, serving the needs of industrial computer scientists, researchers, and computer application specialists for whom the discipline of computing 
          sciences provides indispensable tools with newer programmes being added.</p>

          <p>The Department conducts a Board of Studies every year and offers the syllabus according to the Industry requirements and demands. BCA is an undergraduate 
          programme for candidates wishing to delve into the world of Computer Languages. Being one of the most popular options to get started with a career in Information 
          Technology, this programme gives you an insight into the world of computers and their applications.</p>

          <p>MSc Computer Science is a postgraduate programme provisioning to a group of candidates drawn to probe deeper into the realm of computer science. 
          It aims to prepare young professionals for challenging business opportunities in the IT sector.</p>

          <p>The Department also assists research scholars at various universities such as Bharathiar University, Sri KrishnaDevaraya University, and Mother Teresa University. 
          All faculty members have completed their MPhil and are on the verge of completing their PhD. Both members of the staff and students are actively involved in the research. 
          The students are required to prepare a term paper that is a culmination of a certain amount of research performed by the student on a topic of their choice as approved by 
          the Department. The student is guided continuously during the process by the teachers. All final-year students will have to develop and complete a project for an organisation 
          outside the College. The students need to have a deep awareness of the existing environment and produce workable solutions, ensuring that they have sufficient exposure and 
          preparedness for a challenging career in the field. The Department organises conferences, workshops, Intercollegiate IT fests, FDPs, Guest lectures, Expert talks, and Panel 
          discussions on new trends in computer science and Information technology.</p>
