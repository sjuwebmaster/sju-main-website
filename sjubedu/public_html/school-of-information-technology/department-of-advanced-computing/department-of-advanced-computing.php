           <div class="title-area"><h2 class="fw-bold text-blue mb-3">About</h2></div>
          <p>The Department was established in 2016 with the initiation of a 2-year postgraduate programme in Big Data Analytics. 
          In 2020, the Department introduced a 1-year postgraduate Diploma in Cyber Security in collaboration with HKCS Foundation 
          and an Undergraduate programme BCA(Data Analytics). In 2021, the Department introduced a 1-year postgraduate Diploma in Data Science.</p>

          <p>The MSc (Big Data Analytics) programme enjoys the support and patronage of Tata Consultancy Services Ltd.(TCS), and is built around a state-of-the-art 
          laboratory established with TCS. Professor Bimal Kumar Roy, the eminent academic and researcher, former Director of Indian Statistical Institute (ISI), 
          and Padma Shri awardee, is the guiding spirit and adviser of this program.</p>

          <p>The Department's lab, that can accommodate 60 students and work for extended hours, has a high-speed computing infrastructure to handle big data loads, 
          and a high-definition Cisco video conferencing facility for students and faculty to interact with industry experts, in academic and consulting roles.</p>

          <p>The Department's M.Sc.(Big Data Analytics) program has been an unqualified success; over 300 students have completed the program, and today work in India's 
          top IT establishments, including TCS, in a variety of professional roles undertaking complex projects and assignments in statistical modeling and inference, 
          Machine Learning, Deep Learning and AI.</p>
