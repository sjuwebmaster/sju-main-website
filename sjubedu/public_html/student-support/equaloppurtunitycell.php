    <div class="title-area text-center pb-2"><h2 class="fw-bold mb-3">Equal Oppurtunity  <span class="text-warning">Cell </span></h2></div>
    <p>The Equal Opportunities Cell has been constituted to oversee the effective implementation of policies and programs for disadvantaged groups. The Cell provides guidance and counseling with respect to academic, financial, social, and other matters. The aim of this is to enhance diversity among students, teaching and non-teaching staff. The effective implementation also eliminates any chance of discrimination against individuals or groups. Students from various social backgrounds are encouraged to maintain healthy interpersonal relationships. All efforts are made to sensitize the academic community regarding the problems associated with social exclusion and to see to the fulfillment of the aspirations of the marginalized communities. Greviances if any, related to students from the weaker section of the society, are looked into and addressed.</p>
		
 <p>The Cell also works towards coordination with the Government and other agencies/organizations to mobilize academic and financial resources to provide assistance to students of the disadvantaged groups and adopt measures to ensure due share of utilization by SC/ST in admissions, recruitments (teaching and non-teaching posts).</p>
   	

