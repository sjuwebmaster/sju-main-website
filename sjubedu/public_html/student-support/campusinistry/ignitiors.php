		<p>We are pleased to inform you that the IGNITORS- INTEGRAL FORMATION PROGRAMME  (incorporating the NEP with one credit) was successfully organized for the students of St. Joseph's University, Bengaluru by Campus Ministry till the year 2025. </p>
 <p>According to the implementation draft of the NEP 2021, each student is required to earn one credit every semester under the Skill Enhancement Category. Therefore, the KJES Youth Works organized the program in collaboration with the Campus Ministry of SJU.</p>		
   <p>“IGNITORS” commended as a fire that enkindles other fires in the world today has helped form men and women for and with others. Attending the Ignitors program aids students towards novel learning and broaden ones thought perception. Central to which is the facilitation and interaction provided by professional trainers. This is a program aimed at turning the gaze towards the betterment of society. As a result, our university endeavors to; transform the individual though holistic education which is humane and community centered. Besides, it fosters networks to promote peace, unity, and love in the societies they live in. Additionally it has helped participants to discover their momentum, uniqueness, and guiding principles in life.</p>	
				  
		<p>As a result, the growing consciousness among youngsters that they are ambassadors of justice, equity and change has brought them close towards understanding the notions of human development.</p>
		  <p>Ignitors seek to inspire students to think critically and creatively, and to cultivate their passions for committed and constructive action. The program also aims to encourage young people to dream of a better world and pursue their missions accordingly. The sessions at St. Joseph's University were successful, thanks to the systematic organization of the program and the absence of major glitches. Ignitors 2023 achieved its motto of "A Fire that Kindles other Fires" and uniquely enhanced the students' intellectual and moral development. The involvement of diverse resource persons contributed to the quality of the program. The team was composed of dynamic individuals with expertise in various fields. The sessions covered topics such as Conflict Management and Decision Making, Creative and Critical Thinking, Love and Infatuation, Stress Management and Self-care, and Career Guidance. Various in-class and extracurricular activities gave students a fun learning experience. The program aided students in the formation of their emotional, social, and faith dimensions of life, with the ultimate goal of building a genuine democratic and secular society in India. The feedback received from students was overwhelmingly positive. Ignitors has been a fascinating and challenging experience for the youth in Karnataka, with its forward-looking and integral approach. It is a co-curricular experience that contributes significantly to the integral formation of young people and adds a value component to the educational process. It is a capacity-building program that can eventually lead to a movement of youth working for the betterment of society. IGNITOR is a promising program for the present and the future.</p>
