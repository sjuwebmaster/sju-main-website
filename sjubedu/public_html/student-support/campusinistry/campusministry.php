                      The Campus Ministry at St. Joseph's University, led by lay faculty and a Jesuit spiritual advisor, nurtures the spiritual, moral, and social development of students and staff. Rooted in Ignatian spirituality, the ministry seeks to address the holistic needs of the university community by fostering faith formation, promoting justice, and encouraging service-oriented leadership.</p>

                     <p> Through its various initiatives, the Campus Ministry attends to both the corporal and spiritual needs of the university community. At the spiritual level, Holy Mass is organised every Friday, with special emphasis on First Friday Masses. Special Masses are celebrated for the inauguration of the academic year, as well as on the feasts of St. Joseph, St. Ignatius of Loyola, Christmas, and Ash Wednesday. The ministry also facilitates Lenten services, confessions, and an annual one-day retreat for Catholic students.</p>

                     <p>The Campus Ministry organizes HRD classes for non-Catholic students and theology classes for second-semester Catholic students, fostering inclusivity and holistic formation. It also oversees the midday meal scheme as part of its outreach initiatives.</p>

                     <p>The All India Catholic University Federation (AICUF), functioning under the guidance of the Campus Ministry, is actively involved in organizing Masses, outreach programs, and MAGIS initiatives and participating in workshops and conferences.</p>

                   <p> A group called “SJU Religious,” consisting of religious faculty and students from various congregations, also functions under the ministry and contributes to organizing spiritual activities such as adoration, rosary, and retreats.</p>

                    <p>The units under the Campus Ministry include AICUF, CSA (Christian Student Association), Jesus Youth, and Ignitors (until 2025). The ministry also organizes Christmas celebrations for students and staff, including Christmas Mass.</p>
                  
                    <h4>Campus Ministry Team</h4>

                    <P>The Campus Ministry functions through a dedicated team comprising primarily lay collaborators, with one Jesuit serving as spiritual advisor, who coordinate various spiritual, formative, and outreach activities across the university. Student involvement is ensured through structured student bodies such as CSA, AICUF, and Jesus Youth, each having its own elected student council, fostering leadership and ownership among students.</P>

