           <h3 class="br_title text_blue fw-bold"><span></span>Introduction</h3> 
				
			<div class="mb-3">Jesus Youth is an international Catholic youth movement with a Charismatic Spirituality. It is an initiative of young people, filled with the Holy Spirit,trying to reach out to other young people. The strength of the movement is its special focus on a life centered on the Lord Jesus Christ; beginning with an experience of God, nourished by prayer,the Word of God,the Sacraments, fellowship, and sharing the Good News of Jesus Christ with others. Over the years, Jesus Youth has made a huge impact on different segments of people from various walks of life.</div>
        </div>
		  
	
	 		
	<h4>Origin, History - about the Association/Club</h4>	
			
   <p>In the mid 1970s the flame of the Charismatic Renewal spread to India and to Kerala, the southernmost tip of the Indian subcontinent. The wave of the Holy Spirit gave rise to several youth groups where catholic youth encountered Jesus and the Gospel in a renewed and refreshing way. Gradually these groups began to connect to each other and in 1985, these youth groups came together for a large conference. The conference was called ‘Jesus Youth 85' and the young people who attended the conference began to call themselves ‘Jesus Youth'. These young people shared their experiences to those around, and as they moved into universities, schools, workplaces and cities, they continued to spread the exciting news of Jesus - forming prayer groups and cell groups. The spirituality, approach and creativity of the young people began to spread as a lifestyle. As many among them travelled to different countries, they carried their Jesus Youth lifestyle along with them, leading to the formation of Jesus Youth groups around the world. Today Jesus Youth is present in over 25 countries around the world.
		  
		  </p>	
		<br><h4>Objectives, Vision, and Mission:</h4>
		  
		<p>Campus ministry is one of the most active and lively ministries of the Jesus Youth, having a mission to ‘touch and transform lives in the institutions of higher education'. Today it has a
strong and vibrant presence across India and in different parts of the world. Recalling the powerful exhortation of Holy Father John Paul II, “to be the saints of the new millennium”, this ministry offers youth a platform to become the saints of today, through a lifestyle of prayer and service.</p>
		  
		<br> <h4>The Relevance :</h4> 
		 
		<p>College days are the time when the hearts and minds of students raise the deepest questions on life, meaning, future, love and hope. All are searching for different answers, though often not in the right places. A vibrant, exciting and healthy Catholic Campus Ministry in the college could  help them connect the dots and not miss out on the great adventure that God has in store for them!</p>
<p>JesusYouth strives to bring Jesus to the younger generation in a language they relate with and understand. The Campus ministry continually employs vibrant, relevant and engaging means to
educate students in the Catholic faith. Facilitating universities in their search for wisdom and truth, the ministry also caters to their faculty and staff members. Therefore,the need to increase
the number of evangelisers, students and educators alike,in the“marketplace of ideas” remains high and pressing.</p>
	<br>
	  <h4>The Vision:</h4> 
	 
	 <p> ‘Transforming Education Institutions into Faith Formation Centres' The essence of a Campus ministry can be summed up as evangelisation: “Bringing the message of Christ to the academic world” (‘Empowered by the Spirit'-USCCBdocument,1). This involves bringing students to have an encounter with Jesus Christ and helping them nurture their relationship with Him. It includes, reaching out to those who are away from theChurch and to those who hunger for the truth of the Gospel.</p>
<p>Taking the lead from Pope Paul VI, there is an urgency to go to the very roots of universities to gain souls. We “must not remain on the margins of the academic community, but must accept the
call to bring the light of the Gospel to the very centre of that world”. (‘ Empowered by the Spirit', 28). </p>
<p>The Jesus Youth Campus ministry responds to this by attending to the affective dimension of campus students. By moulding them as disciples of Jesus and instilling within them a passion
for individual conversion and institutional change, the ministry aims to transform institutions of higher education into Catholic Faith Formation centres.</p>
