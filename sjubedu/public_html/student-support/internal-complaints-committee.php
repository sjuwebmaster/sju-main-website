    <p>St Joseph's University is committed to providing a safe environment that is free of sexual harassment (SH) irrespective of gender, race, caste, creed, religion, place of origin, sexual orientation, disability or economic status. It seeks to do so by providing the necessary support, remedial and preventive action and steps to ensure that none of its members and others associated with it are subjected to sexual harassment. This includes setting up of Internal Complainta Committee (ICC) and enforcing âZero Tolerance Policy' on sexual harassment.</p>

<p><strong>It is to be noted that complaints of sexual harassment by any other gender can be addressed to âStudent Grievance Redressal Committee' of St Joseph's University. As per the POSH Act, only women can file a complaint of sexual harassment to Internal Complaints Committee.</strong></p>
	  
	  <h4>THE BACKGROUND:</h4>

<p>All workplaces in India are mandated by law to provide a safe and secure working environment free from sexual harassment for all women.</p>

<p>In a landmark judgment, Vishaka vs. the State of Rajasthan (1997)4, the Supreme Court of India created legally binding guidelines based on the right to equality and dignity accorded under the Indian Constitution as well as by the UN Convention on the Elimination of All Forms of Discrimination against Women (CEDAW).</p>

<p>Since, sexual harassment results in violation of the fundamental rights of a woman to equality as per Articles 14 and 15 and her right to live with dignity as mentioned under Article 21 of the Constitution, the Government of India enacted the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013. The Act is an extension of the Vishaka Guidelines issued by the Supreme Court in 1997.</p>
	  
	<h4>THE POSH ACT</h4>

<p>Having raised the bar of responsibility and accountability in the Vishaka Guidelines, the Supreme Court placed an obligation on workplaces, institutions, and those in positions of responsibility, to uphold working women's fundamental right to equality and dignity at the workplace. Three key obligations were imposed on institutions to meet that standard, namely: Prohibition, Prevention, and Redressal.</p>

<p><strong>Please see the attached document on POSH ACT 2013, for more details. </strong></p> 
   <a href="images/Sexual Harassment Act 2013.pdf" target="_blank" class="btn btn-apply" aria-label="Apply for Bachelor of Commerce program"> Sexual Harassment Act 2013 â'
          </a> <br> <br>
<p>The Supreme Court defined sexual harassment as any unwelcome, sexually determined physical, verbal, or non-verbal conduct. Examples included sexually suggestive remarks about women, demands for sexual Favors, and sexually offensive visuals in the workplace. The definition also covered situations where a woman could be disadvantaged in her workplace as a result of threats relating to employment decisions that could negatively affect her working life.</p>

<p>According to the University Grants Commission Prevention, Prohibition and Redressal of sexual harassment (SH) of women employees and students in Higher Educational Institutions, the constitution of Internal Complaints Committee to address the issues of SH is mandatory.  </p>
	  
	<h5>INTERNAL COMPLAINTS COMMITTEE (ICC) OF ST JOSEPH'S UNIVERSITY:</h5>

 

<p><strong>In case of Physical, Verbal, or any other Sexual Harassment of women, write a mail to icc_posh@office.sju.edu.in and thereafter a written complaint addressed to ICC.</strong></p>

<h4>FUNCTIONS OF THE COMMITTEE</h4>
<p><strong>PREVENTIVE STEPS.</strong></p>
	  
	<p>It will be the endeavour of the committee: </p> 
	 <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To facilitate a safe environment that is free of sexual harassment</li>
<li class="pb-3"><i class="fas fa-check me-2"></i>To create awareness about sexual harassment of women among its employees and students</li>
		   
    </ul> 
	  
	<h4>REMEDIAL STEPS</h4>
	 <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To ensure that the mechanism for registering complaints is safe, accessible, and sensitive.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To take cognizance of complaints about sexual harassment, conduct inquiries, provide assistance and redressal to the victims, recommend penalties, and take action against the harasser, if necessary.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>To advise the competent authority to issue warnings or take the help of the law to stop the harasser, if the complainant consents.</li>
                       <li class="pb-3"><i class="fas fa-check me-2"></i>To seek medical, police, and legal intervention with the consent of the complainant.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>To arrange appropriate psychological, emotional, and physical supportâincluding counselling, security, and other necessary assistanceâfor the victim, if requested.</li>
    </ul> 
	  
	  
	  <h4>PROCEDURE TO BE FOLLOWED BY THE COMMITTEE</h4>
	  
	  <ul class="language-list mt-3 p-0" style="list-style-type:none;">
                       <li class="pb-3"><i class="fas fa-check me-2"></i>The committee shall meet as and when the complaint is received by it. Complaint can be received by any member of the committee.<br>
        <strong>Conciliation:</strong> Before the ICC initiates an inquiry into the complaint, the complainant may request the ICC (in writing/email) to settle the matter between complainant and the respondent through conciliation. However no monitory settlement shall be made the basis of the conciliation. In the event a settlement has been reached and duly recorded by ICC, further inquiry shall not be conducted. In the event that the conciliation fails then the ICC will proceed to formal process of inquiry whose steps are as follows:</li>
                       
    </ul> 
	  
 <h5>Inquiry process: </h5>

	 <ul class="language-list mt-3 p-0" style="list-style-type:none;">
     <li class="pb-3"><i class="fas fa-check me-2"></i>The Committee may direct the complainant to prepare and submit a detailed statement of incidents if the written complaint lacks exactness and required particulars, within two (2) days from such direction or such other period that the Committee may decide. </li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i> The Committee shall direct the accused employee/student to prepare and submit a written response to the complaint/allegations within four (4) days from such direction or such other period as the Committee may decide.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>The Committee shall conduct all proceedings by the principles of natural justice. Both parties will be given a fair and reasonable opportunity to present their case. However, if the respondent chooses not to participate in the proceedings, the Committee reserves the right to proceed ex parte. </li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>The Committee shall allow both parties to produce relevant documents and witnesses to support their case. Documents produced by either party shall be affixed with that party's signature to certify the document as an original/true copy. </li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>The party against whom the document/witness is produced shall be entitled to challenge/cross-examine the same. </li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i> The Committee shall record and consider the evidence produced by both parties.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i> Minutes of all proceedings of the Committee shall be prepared and duly signed by the members of the Committee.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i> The Committee shall record its findings in writing supported with reasons and shall forward the same with its recommendations, to the Vice Chancellor/Management, after the completion of the proceedings before it. In case the Committee finds that the facts discloses that the offense by the accused person is serious and of criminal in nature, this shall be specifically mentioned in the Committee's report. Further, the committee may recommend to the institution to file an FIR with the jurisdiction police.</li>
		 <li class="pb-3"><i class="fas fa-check me-2"></i>If, in the course of the proceedings before it, the Committee is satisfied that a prima facie case of sexual harassment is made out against the accused employee(s)/student and that there is any chance of the recurrence of any such action, or that it is required to do so in the interests of justice, it may, on the request of the complainant or otherwise, disciplinary action could be initiated in the form of, 
		 <ol>
			<li>Warning</li>
			 <li>Written apology</li> 
			 <li>Bond of good behaviour</li> 
			 <li>Adverse remarks in the confidential report</li> 
			 <li> Debarring from supervisory duties</li> 
			 <li>Denial of membership of statutory bodies</li> 
			 <li>Denial of re-employment/readmission</li> 
			 <li>Stopping of increments/promotion/denying admission ticket</li> 
			 <li>Reverting, demotion</li> 
			 <li>Suspension</li> 
			 <li>Dismissal</li>
			 <li>Any other relevant mechanism</li> 
		   </ol>
		 </li>                 
    </ul>   
	  
	 <p> (i) If, at the end of the proceedings before it, the committee is convinced that, the complainant has knowingly brought false charges of sexual harassment against any person, it shall report the same in writing to the Vice Chancellor/Management, with reasons and recommendations of the action to be taken against such person.</p>

<p>(ii) If in the course of the proceedings before it, the Committee is satisfied that any person has retaliated against /victimized the complainant or any person assisting the complainant the committee shall report the same in writing, to the Vice chancellor/Management, with reasons and with recommendations of the action to be taken against such a person.</p>
	  
	<h4>ZERO TOLERANCE POLICY (ZTP) OF ST JOSEPH'S UNIVERSITY AGAINST SEXUAL HARASSMENT </h4> 
	  <ol>
			<li>We are committed to providing a safe environment for all women in the institution free from sexual harassment.</li>
		  <li>We operate under a Zero Tolerance Policy for any form of sexual harassment within the institution. All incidents are treated with utmost seriousness, and every allegation is investigated promptly and thoroughly.</li>
		  <li>Any person involved in SH will face disciplinary action, up to and including dismissal from the institution. Further, the accused can face legal actions like FIR.</li>
		  <li>All complaints of sexual harassment will be treated with confidentiality and respect.</li>
		  <li>In this institution, no one will be victimized for making a complaint of sexual harassment. However, in the event that the inquiry process finds that the complaint is malicious or false, the recommendation for a suitable punitive action will be made against the complainant.</li>
		  
    </ol>
				
			
	  
