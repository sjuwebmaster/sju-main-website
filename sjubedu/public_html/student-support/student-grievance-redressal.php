		<div class="container">
			
			<h4> <strong>PROCEDURE FOR REDRESSAL OF GRIEVANCES BY STUDENT GRIEVANCE REDRESSAL COMMITTEE (SGRC): </strong></h4>	
	  <ul class="language-list mt-3 p-0" style="list-style-type:none;">
            <li class="pb-3"><i class="fas fa-check me-2"></i>The SJU Student Grievance Redressal Committee (SGRC) Form is for grievances pertaining to the students enrolled in the University or applicants seeking admission to be enrolled in the University.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>A complaint/grievance from an aggrieved student relating to the Institution shall be addressed online to the Chairperson of the SGRC only through the SGRC Form.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>On receipt of the online complaint, it will be directed to the SGRC, along with its comments within 15 days of receipt of the complaint on the online portal.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>The SGRC shall send its report with recommendations, if any, to the competent authority of the University and a copy thereof to the aggrieved student within 15 working days from the date of receipt of the complaint.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>The SGRC, as the case may be, will fix a date for hearing the complaint, which will be communicated to the University and the aggrieved student.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>An aggrieved student may appear either in person or authorise a representative to present the case.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>Any student aggrieved by the decision of the SGRC may prefer an appeal to the Ombudsperson, within fifteen days from the date of receipt of such decision.</li>
		   <li class="pb-3"><i class="fas fa-check me-2"></i>Grievances not resolved by the SGRC within the time period provided in these regulations may be referred to the Ombudsperson by the University.</li>
		  
				</ul>
	
		<div class="mt-4">
		<h4> <strong>GENERAL INSTRUCTIONS </strong></h4>	
	  <ul class="language-list mt-3 p-0" style="list-style-type:none;">
            <li class="pb-3"><i class="fas fa-check me-2"></i>Grievances should be made within a week of the matter arising. Grievances raised after these deadlines will be considered late and if you wish that the University considers them then you will need to include a valid reason and evidence of the reason for the delay. You will then be informed either that your reason for delay has been considered valid or that your complaint is out of time.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>All sections of the form should be completed, and any supporting evidence you wish for the committee to consider should be submitted at the time of the hearing.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>Grievances should be described formally and appropriately within the word limit.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>If a student or the representative does not turn up to the hearing, the case will be decided in absentia.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>Appropriate action will be taken against the complainant, where a complaint is found to be false or frivolous.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>The University is not responsible for any amount paid by applicants to any individuals/groups/agencies/organisations, etc outside the University promising admissions.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>The Ombudsperson shall, after giving reasonable opportunities of being heard to the parties concerned on the conclusion of proceedings, pass such order, with reasons thereof, as may be deemed fit to redress the grievance and provide such relief as may be appropriate to the aggrieved student.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>The institution, as well as the aggrieved student, shall be provided with copies of the order under the signature of the Ombudsperson.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>The institution shall comply with the recommendations of the Ombudsperson.</li>
		  <li class="pb-3"><i class="fas fa-check me-2"></i>The Ombudsperson may recommend appropriate action against the complainant, where a complaint is found to be false or frivolous.</li>
		  	     </ul>
